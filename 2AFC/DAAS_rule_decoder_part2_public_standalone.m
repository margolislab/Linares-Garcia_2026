                else
                    % --- KW last resort (not ideal for repeated measures) ---
                    vals = Rw.auc_mean;
                    grp  = nan(height(Rw),1);
                    for i=1:height(Rw), grp(i) = find(trainDays==Rw.day(i), 1); end
                    ok = isfinite(vals) & isfinite(grp);
                    if sum(ok) >= 6 && numel(unique(grp(ok))) >= 2
                        didLearn = true;
                        [pLearn, tbl] = kruskalwallis(vals(ok), grp(ok), 'off');
                        chi2 = tbl{2,5};
                        df   = tbl{2,3};
                        learnLabel = sprintf('KW \\chi^2(%d)=%.3f, p=%.3g %s', ...
                            df, chi2, pLearn, p2stars_(pLearn));

