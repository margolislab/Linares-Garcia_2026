                    pLearn = ct.pValue(rr);
                    beta   = ct.Estimate(rr);
                    learnLabel = sprintf('LME beta=%.4f, p=%.3g %s (n=%d rows)', ...
                        beta, pLearn, p2stars_(pLearn), height(T));

                    fprintf('--- LEARNING (Decoder AUC) %s window ---\n', char(w));
                    fprintf('Day1–Day5 (LME): beta=%.4f, p=%.4g %s  [rows=%d, animals=%d]\n', ...
