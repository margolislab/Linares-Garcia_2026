                        fprintf('Day1–Day5 (KW, WARNING: ignores repeated-measures): chi2(%d)=%.3f, p=%.4g %s\n', ...
                            df, chi2, pLearn, char(p2stars_(pLearn)));
                    end
                end
            end
        end

        % --- overlay learning text + bracket One→Five ---
        if didLearn && isfinite(pLearn)
            text(ax, 0.02, 0.92, ['Day1–5: ' learnLabel], ...
                'Units','normalized','HorizontalAlignment','left','VerticalAlignment','top', ...
                'FontWeight','bold','FontSize',10);

            idOne  = find(strcmp(days,'One'), 1);
