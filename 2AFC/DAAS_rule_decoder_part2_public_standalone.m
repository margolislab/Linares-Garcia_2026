function stats = do_stats_and_print(R, days)
% Standardizes types and prints:
%  - Spearman trend of AUC (All) across days
%  - Paired Five vs Reversal (All)
%  - Per-day Rule1 vs Rule2
%  - Per-day (avg Rule1&Rule2) vs NonRule
%
% Returns a struct "stats" with the same numbers.

    % --- Make types consistent (fixes your ismember error) ---
    if ~isstring(R.day),      R.day      = string(R.day);      end
    if ~isstring(R.window),   R.window   = string(R.window);   end
    if ~isstring(R.category), R.category = string(R.category); end
    if ismember('animal', R.Properties.VariableNames) && ~isstring(R.animal)
        R.animal = string(R.animal);
    end

    wins = ["Sound","Early"];
    stats = struct;

    for wi = 1:numel(wins)
        w = wins(wi);

        % ---------- Trend across days (All) ----------
        S = R(R.window==w & R.category=="All" & ismember(R.day, string(days)), :);
        if ~isempty(S)
            % map days -> numeric order 1..N
            [tf, idx] = ismember(S.day, string(days));
            S = S(tf,:); idx = idx(tf);
            if ~isempty(idx)
                try
                    [rho,p] = corr(idx(:), S.auc_mean(:), 'Type','Spearman', 'Rows','complete');
                catch
                    % very old MATLAB fall-back: rank-transform
                    [~,ri] = sort(idx(:)); [~,ri] = sort(ri);
                    [~,ra] = sort(S.auc_mean(:)); [~,ra] = sort(ra);
                    [rho,p] = corr(ri, ra, 'Rows','complete');
                end
                fprintf('[STATS] %s — Trend All across days: rho=%.3f, p=%.4g %s (n=%d)\n', ...
                        w, rho, p, p2stars_(p), numel(idx));
                stats.(w).trend = struct('rho',rho,'p',p,'n',numel(idx));
            end
        end

        % ---------- Five vs Reversal (All) ----------
        S5 = R(R.window==w & R.category=="All" & R.day=="Five",      {'animal','auc_mean'});
        SR = R(R.window==w & R.category=="All" & R.day=="Reversal",  {'animal','auc_mean'});
        if ~isempty(S5) && ~isempty(SR)
            [aa, i5, iR] = intersect(S5.animal, SR.animal);
            if ~isempty(aa)
                x = S5.auc_mean(i5);  % Five
                y = SR.auc_mean(iR);  % Reversal
                test = 'signrank';
                try
                    p = signrank(x, y);   % paired
                catch
                    p = ranksum(x, y); test = 'ranksum';
                end
                dmed = median(x - y, 'omitnan');
                fprintf('[STATS] %s — Five vs Reversal (All): Δmedian=%.3f, p=%.4g %s (n=%d) [%s]\n', ...
                        w, dmed, p, p2stars_(p), numel(aa), test);
                stats.(w).five_vs_rev = struct('n',numel(aa),'medianDelta',dmed,'p',p,'test',test);
            end
        end

        % ---------- Per-day Rule1 vs Rule2 & (R1&R2) vs NonRule ----------
        for di = 1:numel(days)
            dd = string(days{di});
            T1  = R(R.window==w & R.day==dd & R.category=="Rule1",   {'animal','auc_mean'});
            T2  = R(R.window==w & R.day==dd & R.category=="Rule2",   {'animal','auc_mean'});
            TNR = R(R.window==w & R.day==dd & R.category=="NonRule", {'animal','auc_mean'});

            % R1 vs R2 (paired by animal)
            if ~isempty(T1) && ~isempty(T2)
                [aa, i1, i2] = intersect(T1.animal, T2.animal);
                if numel(aa) >= 3
                    x = T1.auc_mean(i1); y = T2.auc_mean(i2);
                    test = 'signrank';
                    try, p12 = signrank(x, y); catch, p12 = ranksum(x, y); test = 'ranksum'; end
                    dmed = median(x - y, 'omitnan');
                    fprintf('[STATS] %s — %s: R1 vs R2: Δmedian=%.3f, p=%.4g %s (n=%d) [%s]\n', ...
                            w, dd, dmed, p12, p2stars_(p12), numel(aa), test);
                    stats.(w).(dd).R1vR2 = struct('n',numel(aa),'medianDelta',dmed,'p',p12,'test',test);
                end
            end

            % (R1&R2 avg) vs NonRule (paired by animal where NonRule present)
            if ~isempty(TNR) && (~isempty(T1) || ~isempty(T2))
                A = unique([T1.animal; T2.animal]);
                if ~isempty(A)
                    % average R1/R2 per animal when present
                    [tf1, j1] = ismember(A, T1.animal); r1 = nan(numel(A),1); r1(tf1) = T1.auc_mean(j1(tf1));
                    [tf2, j2] = ismember(A, T2.animal); r2 = nan(numel(A),1); r2(tf2) = T2.auc_mean(j2(tf2));
                    rr = nanmean([r1 r2], 2);

                    [aa, iR, iN] = intersect(A, TNR.animal);
                    x = rr(iR); y = TNR.auc_mean(iN);
                    m = isfinite(x) & isfinite(y);
                    if sum(m) >= 3
                        test = 'signrank';
                        try, pRN = signrank(x(m), y(m)); catch, pRN = ranksum(x(m), y(m)); test = 'ranksum'; end
                        dmed = median(x(m) - y(m), 'omitnan');
                        fprintf('[STATS] %s — %s: (R1&R2) vs NonRule: Δmedian=%.3f, p=%.4g %s (n=%d) [%s]\n', ...
                                w, dd, dmed, pRN, p2stars_(pRN), sum(m), test);
                        stats.(w).(dd).R12vNR = struct('n',sum(m),'medianDelta',dmed,'p',pRN,'test',test);
                    end
                end
            end
        end
    end
end


function q = bh_fdr_local(p)
p = p(:); v = isfinite(p);
q = nan(size(p));
if any(v)
    try
        q(v) = mafdr(p(v),'BHFDR',true);
    catch
        % fallback BH
        x = p(v);
        [xs,idx] = sort(x);
        m = numel(xs); r = (1:m)';
        qtmp = xs.*m./r;
        for i=m-1:-1:1, qtmp(i) = min(qtmp(i), qtmp(i+1)); end
        y = nan(size(xs)); y(idx)=min(qtmp,1);
        q(v)=y;
    end
end
end

