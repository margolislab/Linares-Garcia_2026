            if exist('stats','var') && isstruct(stats) && isfield(stats,'day5rev') && isfield(stats.day5rev, char(w))
                p5r = stats.day5rev.(char(w)).p;
                if isfinite(p5r)
                    draw_bracket(ax, idFive, idRev, yb, p2stars_(p5r));
                end
            end
        end

    else
        axis(ax,'off'); title(ax, sprintf('%s window — no decodable models', w));
    end
end
