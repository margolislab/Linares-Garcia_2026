function DAAS_rule_decoder_part2_public_standalone(NewData2_DAAS, params, ruleselsummary)
% 
%
% DAAS_RULE_DECODER_PART2_PUBLIC_STANDALONE
%
% Public manuscript-figure version of the 2AFC rule-decoding analysis.
%
% This function performs within-day decoding of the active task rule
% (Rule 1 versus Rule 2) from trial-wise mean calcium activity. It uses
% processed calcium traces and the Part 1 rule-selectivity summary to
% compare decoder performance across neuronal categories.
%
% The code is intentionally restricted to manuscript figure outputs. It
% excludes exploratory plots, optional model variants, and print-only
% analyses that are not required to reproduce the paper figures.
%
% -------------------------------------------------------------------------
% Manuscript outputs generated by this function
% -------------------------------------------------------------------------
%   Fig. 7D / Fig. 7H
%       Decoder AUC across learning days using all neurons.
%
%   Fig. 7E / Fig. 7I
%       Sound-window versus early-post-sound decoder AUC for rule-preferring
%       and non-rule task-modulated neurons.
%
%   Supplementary Fig. 5D / Supplementary Fig. 5F
%       Per-day decoder AUC bars for Rule1, Rule2, and NonRule categories.
%
% -------------------------------------------------------------------------
% Expected inputs
% -------------------------------------------------------------------------
%   NewData2_DAAS
%       Processed data structure organized as:
%           NewData2_DAAS.(Animal).(Day){neuron}
%
%       Each neuron entry is expected to contain:
%           .data        [nTrials x nFrames] trial-wise calcium activity
%           .sound1Mask  logical vector for correct Rule 1 / Sound 1 trials
%           .sound2Mask  logical vector for correct Rule 2 / Sound 2 trials
%
%   params
%       Parameter structure. Required fields:
%           params.days
%           params.nFrames
%           params.fs
%           params.win.sound
%
%       Common decoder fields:
%           params.decoder.kfold
%           params.decoder.repeats
%           params.decoder.n_shuffles
%           params.decoder.save_dir
%
%   Summary
%       Optional Part 1 rule-selectivity summary table. If omitted, this
%       function tries to load a summary table from params.rule.save_dir.
%
% Notes:
%   This file is standalone in the MATLAB sense: the local helper functions
%   required by this analysis are included below the main function.

%% ------------------------------------------------------------------------
% 1. Parameters and defaults
% -------------------------------------------------------------------------

if nargin < 2
    params = struct();
end

days = getf(params, 'days', []);
if isempty(days)
    error('params.days is required, for example: {''One'',''Two'',''Three'',''Four'',''Five''}.');
end

T      = getf(params, 'nFrames', 89);
fs     = getf(params, 'fs', 16);
Wsound = getf(getf(params, 'win', struct()), 'sound', 32:40);

rule = getf(params, 'rule', struct());
correctOnly = getf(rule, 'correct_only', true);

% Directory containing the Part 1 rule-selectivity summary.
saveDir1 = getf(rule, 'save_dir', fullfile(pwd, 'rule_selectivity_public'));

% Decoder settings.
dec = getf(params, 'decoder', struct());
decDir = getf(dec, 'save_dir', fullfile(saveDir1, 'decoder_part2_public'));
if ~exist(decDir, 'dir')
    mkdir(decDir);
end

rngSeed = getf(dec, 'rng_seed', 42);
K = getf(dec, 'kfold', 5);
Nrep = getf(dec, 'repeats', 5);
Bnull = getf(dec, 'n_shuffles', 1000);
minCells = getf(dec, 'min_neurons', 1);
maxPerCls = getf(dec, 'max_trials_per_class', 150);

saveFigs = getf(dec, 'save_figs', true);
saveTables = getf(dec, 'save_tables', true);
closeFigs = getf(dec, 'close_figs', false);
figFormats = getf(dec, 'fig_formats', {'png'});

if ischar(figFormats) || isstring(figFormats)
    figFormats = cellstr(figFormats);
end

% Early window: first 0.5 s after the sound window.
tone_off = max(Wsound);
Wearly = tone_off + 1 : min(tone_off + round(0.5 * fs), T);

WinList = {'Sound', 'Early'};
Wbins = {clipW(Wsound, T), clipW(Wearly, T)};

% Decoder categories. Rule1/Rule2/NonRule are defined using the Part 1
% Sound-window rule-selectivity summary.
CATS = {'All', 'Rule1', 'Rule2', 'NonRule'};

fprintf('\n[Decoder public] Output directory: %s\n', decDir);
fprintf('[Decoder public] Sound window: frames %d-%d\n', min(Wsound), max(Wsound));
fprintf('[Decoder public] Early window: frames %d-%d\n', min(Wearly), max(Wearly));
fprintf('[Decoder public] CV: %d-fold, %d repeats, %d shuffles\n\n', K, Nrep, Bnull);

%% ------------------------------------------------------------------------
% 2. Load or standardize Part 1 summary
% -------------------------------------------------------------------------

if nargin < 3 || isempty(ruleselsummary)
    summaryFile = getf(dec, 'summary_file', '');

    candidateFiles = {};
    if ~isempty(summaryFile)
        candidateFiles{end+1} = summaryFile; %#ok<AGROW>
    end

    candidateFiles{end+1} = fullfile(saveDir1, 'source_rule_selectivity_summary_all_windows.csv');
    candidateFiles{end+1} = fullfile(saveDir1, 'source_sound_rule_summary_for_figures.csv');
    candidateFiles{end+1} = fullfile(saveDir1, 'rule_sel_summary.csv');

    loaded = false;
    for i = 1:numel(candidateFiles)
        if exist(candidateFiles{i}, 'file')
            ruleselsummary = readtable(candidateFiles{i});
            fprintf('[Decoder public] Loaded Part 1 summary: %s\n', candidateFiles{i});
            loaded = true;
            break;
        end
    end

    if ~loaded
        error(['No Summary table was provided and no summary file was found. ', ...
            'Pass Summary directly or set params.decoder.summary_file.']);
    end
end

ruleselsummary.animal = string(ruleselsummary.animal);
ruleselsummary.day = string(ruleselsummary.day);
ruleselsummary.window = string(ruleselsummary.window);

if ~ismember('sig_task', ruleselsummary.Properties.VariableNames)
    ruleselsummary.sig_task = false(height(ruleselsummary), 1);
end

%% ------------------------------------------------------------------------
% 3. Build decoder rows for each animal, day, window, and neuron category
% -------------------------------------------------------------------------
% For each animal/day/window/category:
%   1) build a trial-by-neuron feature matrix;
%   2) balance Rule 1 and Rule 2 trials;
%   3) train repeated cross-validated logistic classifiers;
%   4) compare observed AUC against label-shuffled null distributions.

Rows = table('Size', [0 17], 'VariableTypes', ...
    {'string','string','string','string','double','double','double','double','double','double','double','double','double','double','double','double','double'}, ...
    'VariableNames', {'animal','day','window','category','nTrials','nNeurons','auc_mean','auc_sem','acc_mean','acc_sem', ...
                      'p_shuffle','auc_null_mean','auc_null_sd','auc_med','auc_q1','auc_q3','nReps'});

NullStore = struct();

rng(rngSeed);
animals = fieldnames(NewData2_DAAS);

for ai = 1:numel(animals)
    animalName = animals{ai};

    if ~isstruct(NewData2_DAAS.(animalName))
        continue;
    end

    for di = 1:numel(days)
        dayName = days{di};

        if ~isfield(NewData2_DAAS.(animalName), dayName) || isempty(NewData2_DAAS.(animalName).(dayName))
            fprintf('[Decoder public] Skipping %s / %s: no data found.\n', animalName, dayName);
            continue;
        end

        E = NewData2_DAAS.(animalName).(dayName);

        [ruleLbl, srcIdx] = get_rule_labels(E, correctOnly);
        if isempty(ruleLbl)
            fprintf('[Decoder public] Skipping %s / %s: no rule labels found.\n', animalName, dayName);
            continue;
        end

        keep = ruleLbl == 1 | ruleLbl == 2;
        ruleLbl = ruleLbl(keep); %#ok<NASGU>

        SdaySound = ruleselsummary(ruleselsummary.animal == animalName & ruleselsummary.day == dayName & ruleselsummary.window == "Sound", :);
        catMask = build_category_masks(SdaySound, numel(E));

        for wi = 1:numel(WinList)
            windowName = WinList{wi};
            Wv = Wbins{wi};

            if isempty(Wv)
                continue;
            end

            try
                [X, y, okCols] = build_trial_feature_matrix(E, srcIdx, keep, Wv, T);
            catch ME
                warning('[Decoder public] Skipping %s / %s / %s: %s', ...
                    animalName, dayName, windowName, ME.message);
                continue;
            end

            if isempty(X)
                continue;
            end

            catHere = align_masks(catMask, okCols);

            for ci = 1:numel(CATS)
                categoryName = CATS{ci};
                colMask = catHere.(categoryName);

                if sum(colMask) < minCells
                    continue;
                end

                Xsub = X(:, colMask);
                [Xb, yb] = balance_classes(Xsub, y, maxPerCls);

                if numel(unique(yb)) < 2 || size(Xb, 1) < max(K, 10)
                    continue;
                end

                [auc_vec, acc_vec] = cv_decode_logistic(Xb, yb, K, Nrep);
                auc_null = shuffle_null_auc(Xb, yb, K, Bnull);

                r = table( ...
                    string(animalName), string(dayName), string(windowName), string(categoryName), ...
                    double(numel(yb)), double(size(Xb, 2)), ...
                    mean(auc_vec, 'omitnan'), sem(auc_vec), ...
                    mean(acc_vec, 'omitnan'), sem(acc_vec), ...
                    right_tail_p(mean(auc_vec, 'omitnan'), auc_null), ...
                    mean(auc_null, 'omitnan'), std(auc_null, 0, 'omitnan'), ...
                    median(auc_null, 'omitnan'), quantile(auc_null, 0.25), quantile(auc_null, 0.75), ...
                    double(numel(auc_vec)), ...
                    'VariableNames', Rows.Properties.VariableNames);

                Rows = [Rows; r]; %#ok<AGROW>

                key = matlab.lang.makeValidName(sprintf('%s__%s__%s', dayName, windowName, categoryName));
                if ~isfield(NullStore, key)
                    NullStore.(key) = [];
                end
                NullStore.(key) = [NullStore.(key); auc_null(:)];
            end
        end
    end
end

if isempty(Rows) || height(Rows) == 0
    error('No decoder rows were generated. Check the input data, Summary table, and decoder parameters.');
end

if saveTables
    writetable(Rows, fullfile(decDir, 'source_decoder_per_animal_rows.csv'));
end

fprintf('[Decoder public] Decoder rows generated: %d\n', height(Rows));

%% ------------------------------------------------------------------------
% 4. Aggregate decoder performance and compute figure statistics
% -------------------------------------------------------------------------

Agg = day_aggregate(Rows, NullStore);

if saveTables
    writetable(Agg, fullfile(decDir, 'source_decoder_day_summary.csv'));
end

print_decoder_agg_check(Agg, days);

% These statistics are used by the original figure functions for some
% annotations and are retained because they support manuscript figures.
stats = do_stats_and_print(Rows, days);

%% ------------------------------------------------------------------------
% 5. Generate manuscript figure outputs
% -------------------------------------------------------------------------

if saveFigs
    % Fig. 7D/H: all-neuron decoder AUC across days.
    run_figure_block('Fig7D_H_decoder_auc_across_days', @() ...
        save_public_figure(fig_decoder_auc_across_days(Agg, Rows, days, stats), decDir, ...
        'Fig7D_H_decoder_auc_across_days', figFormats, closeFigs));

    % Supplementary Fig. 5D/F: category-specific decoder AUC bars.
    run_figure_block('SuppFig5D_F_decoder_category_bars', @() ...
        save_public_figure(fig_decoder_category_bars(Agg, Rows, days, stats), decDir, ...
        'SuppFig5D_F_decoder_category_bars', figFormats, closeFigs));

    % Fig. 7E/I: Sound versus Early decoder AUC for rule-preferring and
    % non-rule task-modulated neurons.
    run_figure_block('Fig7E_I_decoder_sound_vs_early_rulepref_nonrule', @() ...
        save_public_figure(fig_decoder_sound_vs_early_rulepref_nonrule(Rows, days), decDir, ...
        'Fig7E_I_decoder_sound_vs_early_rulepref_nonrule', figFormats, closeFigs));
end

fprintf('\n[Decoder public] Finished manuscript decoder analysis.\n');
fprintf('[Decoder public] Outputs saved in: %s\n\n', decDir);

end

%% ========================================================================
% Public file-management helper functions
% ========================================================================

function run_figure_block(label, functionHandle)
% Run one manuscript-figure block and report clear warnings if it fails.

try
    fprintf('[Decoder public] Generating %s...\n', label);
    functionHandle();
catch ME
    warning('[Decoder public] %s failed: %s', label, ME.message);
end
end

function save_public_figure(h, saveDir, baseName, figFormats, closeFigs)
% Save a figure in one or more formats using manuscript-facing filenames.

if isempty(h) || ~ishandle(h)
    h = gcf;
end

for i = 1:numel(figFormats)
    ext = char(figFormats{i});
    ext = erase(ext, '.');
    outFile = fullfile(saveDir, sprintf('%s.%s', baseName, ext));
    saveas(h, outFile);
end

if closeFigs
    close(h);
end
end

%% ========================================================================
% Original local helper functions required by the public decoder pipeline
% ========================================================================
% These helper functions are copied from the original decoder analysis file
% so this public version can run as a single MATLAB file. The main function
% above only calls the helpers needed to generate the manuscript figures.

function [X, y, okCols] = build_trial_feature_matrix(E, srcIdx, keep, W, T, varargin)
% Returns a trial-by-neuron matrix (mean ΔF/F over W) on the largest common
% set of labeled trials shared by ALL usable neurons. Prints diagnostics.

    if nargin < 6 || isempty(varargin{1})
        if ~isfield(E{srcIdx}, 'sound1Mask') || ~isfield(E{srcIdx}, 'sound2Mask')
            error('build_trial_feature_matrix: source entry lacks sound1Mask/sound2Mask.');
        end
        s1 = logical(E{srcIdx}.sound1Mask);
        s2 = logical(E{srcIdx}.sound2Mask);
        L  = nan(size(s1));
        L(s1) = 1; L(s2) = 2;
        both = s1 & s2; if any(both), L(both) = 1; end
        ruleLblAll = L(:);
    else
        ruleLblAll = varargin{1}(:);
    end

    selIdx = find(keep);
    if isempty(selIdx)
        error('build_trial_feature_matrix: no labeled trials after KEEP mask.');
    end

    % usable neurons and their trial counts
    N = numel(E);
    usable = false(1,N);
    nTrialsEach = zeros(1,N);
    hasWin = false(1,N);
    for n = 1:N
        en = E{n};
        if ~isstruct(en) || ~isfield(en,'data') || isempty(en.data), continue; end
        [nTr, Tn] = size(en.data);
        if nTr > 0
            usable(n) = true;
            nTrialsEach(n) = nTr;
            hasWin(n) = any(W >= 1 & W <= Tn);
        end
    end
    if ~any(usable)
        error('build_trial_feature_matrix: no neurons have data.');
    end

    Nt_allSrc = numel(ruleLblAll);
    Nt_common = min([Nt_allSrc, min(nTrialsEach(usable))]);

    % DIAGNOSTICS header
    fprintf('[BTM] %s/%s/%s\n','(animal?)','(day?)','(window?)'); % filled by caller via logs above
    % Above line kept generic—your callsite already prints detailed headers.

    % small pretty print
    fprintf('      usableNeurons=%d / %d | withWindowOverlap=%d\n', sum(usable), N, sum(hasWin));
    Tnz = nTrialsEach(usable);
    fprintf('      per-neuron frames: min=%d, max=%d\n', T, T); %#ok<NASGU>
    fprintf('      labelLen=%d | minTrialsUsable=%d | Nt_common=%d\n', Nt_allSrc, min(nTrialsEach(usable)), Nt_common);

    if Nt_common <= 0
        error('build_trial_feature_matrix: no common trials across usable neurons.');
    end

    selIdxCommon = selIdx(selIdx <= Nt_common);
    if isempty(selIdxCommon)
        fprintf('[BTM][DIAG] — No labeled trials remain after common-span trim.\n');
        error('build_trial_feature_matrix: labeled trials exceed common trial span.');
    end
    y = ruleLblAll(selIdxCommon);
    fprintf('      labeledCorrectTrials=%d | afterCommonTrim=%d\n', numel(selIdx), numel(selIdxCommon));

    % assemble X
    nCols = sum(usable);
    X = nan(numel(selIdxCommon), nCols);
    okCols = false(1,N);
    col = 0;
    for n = 1:N
        if ~usable(n), continue; end
        en = E{n};
        [~, Tn] = size(en.data);
        Wc = W(W >= 1 & W <= Tn);
        if isempty(Wc), continue; end
        v = mean(en.data(1:Nt_common, Wc), 2, 'omitnan');   % [Nt_common x 1]
        fv = v(selIdxCommon);
        if all(~isfinite(fv)), continue; end
        col = col + 1;
        X(:, col) = fv;
        okCols(n) = true;
    end
    fprintf('      builtCols=%d | validRows=%d | class1=%d | class2=%d\n', col, size(X,1), sum(y==1), sum(y==2));

    X = X(:, 1:col);
    if isempty(X) || col==0
        fprintf('[BTM][DIAG] — No neurons yielded finite features in this window.\n');
        error('build_trial_feature_matrix: no neurons had usable data for the given window.');
    end
    validRows = all(isfinite(X), 2);
    X = X(validRows, :);
    y = y(validRows);

    if size(X,1) < 5 || numel(unique(y)) < 2 || size(X,2) < 2
        error('build_trial_feature_matrix: matrix too small after cleaning (rows=%d, cols=%d, classes=%d).', size(X,1), size(X,2), numel(unique(y)));
    end
end

function catMask = build_category_masks(SdaySnd, Nneurons)
% Using Part-1 Summary (SOUND window) to mark categories.
% IMPORTANT: 'All' must be true even if Summary is empty.

catMask = struct('All', true(Nneurons,1), ...   % <-- set All=true upfront
                 'Rule1', false(Nneurons,1), ...
                 'Rule2', false(Nneurons,1), ...
                 'NonRule', false(Nneurons,1));

if isempty(SdaySnd)
    % No info for Rule1/Rule2/NonRule; keep them false, but All stays true.
    return;
end

% Safety: ensure 'neuron' is valid indexing into 1..Nneurons
if ~ismember('neuron', SdaySnd.Properties.VariableNames)
    warning('Summary missing ''neuron'' column; only "All" category will be used.');
    return;
end

nList = double(SdaySnd.neuron(:));
validIdx = nList>=1 & nList<=Nneurons & isfinite(nList);
nList = nList(validIdx);

% Rule-pref (sig_FDR & auROC thresholds)
hasSigFDR = ismember('sig_FDR', SdaySnd.Properties.VariableNames);
hasAuROC  = ismember('auROC',  SdaySnd.Properties.VariableNames);
if ~(hasSigFDR && hasAuROC)
    warning('Summary missing sig_FDR/auROC; Rule1/Rule2 left empty.');
else
    r1_rows = SdaySnd.sig_FDR & SdaySnd.auROC>0.5;
    r2_rows = SdaySnd.sig_FDR & SdaySnd.auROC<0.5;
    r1_rows = r1_rows(validIdx);
    r2_rows = r2_rows(validIdx);
    catMask.Rule1(nList(r1_rows)) = true;
    catMask.Rule2(nList(r2_rows)) = true;
end

% Non-rule (sig_task & ~sig_FDR) if present
if ismember('sig_task', SdaySnd.Properties.VariableNames) && hasSigFDR
    nr_rows = SdaySnd.sig_task & ~SdaySnd.sig_FDR;
    nr_rows = nr_rows(validIdx);
    catMask.NonRule(nList(nr_rows)) = true;
end
end


function catHere = align_masks(catMask, okCols)
catHere = structfun(@(v) v(okCols), catMask, 'UniformOutput', false);
end

function [Xb, yb] = balance_classes(X, y, maxPerCls)
if nargin < 3 || isempty(maxPerCls), maxPerCls = Inf; end
idx1 = find(y==1); idx2 = find(y==2);
nmin = min(numel(idx1), numel(idx2));
nmin = min(nmin, maxPerCls);
if nmin < 1, Xb=[]; yb=[]; return; end
idx1 = idx1(randperm(numel(idx1), nmin));
idx2 = idx2(randperm(numel(idx2), nmin));
sel  = sort([idx1; idx2]);
Xb = X(sel, :);
yb = y(sel);
end

function [auc_vec, acc_vec] = cv_decode_logistic(X, y, K, Nrep)
auc_vec = zeros(Nrep,1);
acc_vec = zeros(Nrep,1);
y = double(y);  % labels {1,2}

for r = 1:Nrep
    try
        cv = cvpartition(categorical(y),'KFold',K);
    catch
        cv = cvpartition(numel(y),'KFold',K);
    end
    auc_f = zeros(K,1);
    acc_f = zeros(K,1);
    for k = 1:K
        trainIdx = training(cv,k);
        testIdx  = test(cv,k);
        Xtr = X(trainIdx,:); Xte = X(testIdx,:);
        ytr = y(trainIdx);   yte = y(testIdx);

        % standardize from train
        mu = mean(Xtr,1);  sd = std(Xtr,0,1);  sd(sd==0) = 1;
        Xtr = (Xtr - mu)./sd;  Xte = (Xte - mu)./sd;

        mdl = fitclinear(Xtr, ytr, 'Learner','logistic', ...
                         'Regularization','ridge','Lambda',1, ...
                         'ClassNames',[1 2]);
        [~,score] = predict(mdl, Xte);
        % score(:,2) is probability of class '2' for logistic
        s = score(:,2);
        auc_f(k) = quickAUC(s, yte==2);
        yhat = double(s >= 0.5) + 1; % map to {1,2}
        acc_f(k) = mean(yhat==yte);
    end
    auc_vec(r) = mean(auc_f,'omitnan');
    acc_vec(r) = mean(acc_f,'omitnan');
end
end

function auc = shuffle_null_auc(X, y, K, B)
auc = zeros(B,1);
for b = 1:B
    ysh = y(randperm(numel(y)));
    try
        cv = cvpartition(categorical(ysh),'KFold',K);
    catch
        cv = cvpartition(numel(ysh),'KFold',K);
    end
    auc_f = zeros(K,1);
    for k = 1:K
        tr = training(cv,k); te = test(cv,k);
        Xtr = X(tr,:); Xte = X(te,:); ytr = ysh(tr); yte = ysh(te);
        mu = mean(Xtr,1); sd = std(Xtr,0,1); sd(sd==0)=1;
        Xtr = (Xtr - mu)./sd;  Xte = (Xte - mu)./sd;
        mdl = fitclinear(Xtr, ytr, 'Learner','logistic', ...
                         'Regularization','ridge','Lambda',1, ...
                         'ClassNames',[1 2]);
        [~,score] = predict(mdl, Xte);
        auc_f(k) = quickAUC(score(:,2), yte==2);
    end
    auc(b) = mean(auc_f,'omitnan');
end
end

function a = quickAUC(scores, labelsLogical)
% Mann–Whitney U / rank-based AUC (fast, no perfcurve dependency)
labelsLogical = logical(labelsLogical);
sPos = scores(labelsLogical);
sNeg = scores(~labelsLogical);
if isempty(sPos) || isempty(sNeg)
    a = NaN; return;
end
r = tiedrank([sPos; sNeg]);
nPos = numel(sPos); nNeg = numel(sNeg);
Rpos = sum(r(1:nPos));
U = Rpos - nPos*(nPos+1)/2;
a = U / (nPos*nNeg);
end

function v = sem(x)
v = std(x,0,'omitnan')/max(1,sqrt(sum(isfinite(x))));
end

function p = right_tail_p(obs, nullAUC)
if isempty(nullAUC) || ~isfinite(obs), p = NaN; return; end
p = mean(nullAUC >= obs);
end

function v = getf(S, fld, default)
if nargin < 3, default = []; end
if isstruct(S) && isfield(S,fld) && ~isempty(S.(fld))
    v = S.(fld);
else
    v = default;
end
end

function Wc = clipW(W, T)
if isempty(W), Wc = [];
else, Wc = W(W >= 1 & W <= T);
end
end

function [ruleLbl, fromIdx] = get_rule_labels(E, correctOnly)
ruleLbl = []; fromIdx = [];
if isempty(E) || ~iscell(E), return; end
for n = 1:numel(E)
    en = E{n};
    if ~isstruct(en) || ~isfield(en,'data') || isempty(en.data), continue; end
    useAll = ~correctOnly && isfield(en,'sound1Mask_all') && isfield(en,'sound2Mask_all');
    if useAll
        s1 = logical(en.sound1Mask_all); s2 = logical(en.sound2Mask_all);
    elseif isfield(en,'sound1Mask') && isfield(en,'sound2Mask')
        s1 = logical(en.sound1Mask);     s2 = logical(en.sound2Mask);
    else
        continue;
    end
    L = nan(size(s1)); L(s1)=1; L(s2)=2; both = s1 & s2; if any(both), L(both)=1; end
    ruleLbl = L(:); fromIdx = n; return;
end
end

function Agg = day_aggregate(Rows, NullStore)
% Manual aggregator (no groupsummary). Returns table:
%   day, window, category, nModels, auc_mean, auc_sem, p_vs_shuffle
if isempty(Rows) || height(Rows)==0
    Agg = table('Size',[0 7], ...
        'VariableTypes',{'string','string','string','double','double','double','double'}, ...
        'VariableNames',{'day','window','category','nModels','auc_mean','auc_sem','p_vs_shuffle'});
    return;
end

Rows.day = string(Rows.day);
Rows.window = string(Rows.window);
Rows.category = string(Rows.category);

keys = unique(Rows(:,{'day','window','category'}),'rows');
n = height(keys);
Agg = table('Size',[n 7], ...
    'VariableTypes',{'string','string','string','double','double','double','double'}, ...
    'VariableNames',{'day','window','category','nModels','auc_mean','auc_sem','p_vs_shuffle'});

for i = 1:n
    d = keys.day(i); w = keys.window(i); c = keys.category(i);
    idx = Rows.day==d & Rows.window==w & Rows.category==c;
    vals = Rows.auc_mean(idx);
    Agg.day(i) = d; Agg.window(i) = w; Agg.category(i) = c;
    Agg.nModels(i) = sum(isfinite(vals));
    Agg.auc_mean(i) = mean(vals,'omitnan');
    Agg.auc_sem(i)  = std(vals,0,'omitnan')/max(1,sqrt(sum(isfinite(vals))));

    % ---- pooled shuffle-null p (supports both hierarchical and flattened keys)
    p = NaN;
    dkey = char(d); wkey = char(w); ckey = char(c);

    % try flattened "D__W__C"
    flatKey = matlab.lang.makeValidName(sprintf('%s__%s__%s', dkey, wkey, ckey));
    if isstruct(NullStore) && isfield(NullStore, flatKey)
        nullAUC = NullStore.(flatKey);
    elseif isstruct(NullStore) && isfield(NullStore, dkey) ...
          && isfield(NullStore.(dkey), wkey) ...
          && isfield(NullStore.(dkey).(wkey), ckey)
        nullAUC = NullStore.(dkey).(wkey).(ckey);
    else
        nullAUC = [];
    end

    mu = Agg.auc_mean(i);
    if ~isempty(nullAUC) && isfinite(mu)
        % two-sided around 0.5 (how far from chance)
        p = mean( abs(nullAUC - 0.5) >= abs(mu - 0.5) );
    end
    Agg.p_vs_shuffle(i) = p;
end
end

