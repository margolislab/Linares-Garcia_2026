function stats = do_clustered_pool_tests(R, days)
% Cluster-aware tests using animal as the independent unit.
% Uses all available days to stabilize estimates within animal.

trainDays = string({'One','Two','Three','Four','Five'});
wins      = string({'Sound','Early'});

% ensure strings
R.animal   = string(R.animal);
R.day      = string(R.day);
R.window   = string(R.window);
R.category = string(R.category);

animals = unique(R.animal);
stats = struct();

for wi = 1:numel(wins)
    w = wins(wi);

    %% (A) Trend across training days (All neurons), per-animal Spearman, then signrank vs 0
    rho_list = [];
    for ai = 1:numel(animals)
        a = animals(ai);
        idx = R.animal==a & R.window==w & R.category=="All" & ismember(R.day, trainDays);
        if any(idx)
            dnames = R.day(idx);
            yvals  = R.auc_mean(idx);
            % align to numeric day order 1..5
            [ok, di] = ismember(dnames, trainDays);
            di = di(ok); yv = yvals(ok);
            % guard: need >=3 points for a meaningful rho
            if numel(di) >= 3
                [rho,~] = corr(di(:), yv(:), 'Type','Spearman','Rows','complete');
                if isfinite(rho), rho_list(end+1,1) = rho; end %#ok<AGROW>
            end
        end
    end
    p_trend = NaN; med_rho = NaN; n_trend = numel(rho_list);
    if n_trend >= 1
        try
            p_trend = signrank(rho_list, 0);
        catch
            % fallback: binomial sign test
            s = sum(rho_list>0);
            p_trend = 2*binocdf(min(s, n_trend-s), n_trend, 0.5);
        end
        med_rho = median(rho_list,'omitnan');
    end
    stats.(w).trend = struct('n',n_trend,'median_rho',med_rho,'p',p_trend);

    %% (B) Five vs Reversal (All neurons), paired within animal
    deltas = nan(numel(animals),1);
    for ai = 1:numel(animals)
        a = animals(ai);
        y5 = mean(R.auc_mean(R.animal==a & R.window==w & R.category=="All" & R.day=="Five"),'omitnan');
        yR = mean(R.auc_mean(R.animal==a & R.window==w & R.category=="All" & R.day=="Reversal"),'omitnan');
        if isfinite(y5) && isfinite(yR)
            deltas(ai) = y5 - yR;
        end
    end
    val = deltas(isfinite(deltas));
    p_pair = NaN; med_delta = NaN;
    if ~isempty(val)
        try
            p_pair = signrank(val, 0);
        catch
            s = sum(val>0); nN = numel(val);
            p_pair = 2*binocdf(min(s, nN-s), nN, 0.5);
        end
        med_delta = median(val,'omitnan');
    end
    stats.(w).five_vs_rev = struct('n',numel(val),'median_delta',med_delta,'p',p_pair);

    %% (C) Rule1 vs Rule2 (average across training days, per animal)
    deltas = nan(numel(animals),1);
    for ai = 1:numel(animals)
        a = animals(ai);
        r1 = mean(R.auc_mean(R.animal==a & R.window==w & R.category=="Rule1" & ismember(R.day,trainDays)), 'omitnan');
        r2 = mean(R.auc_mean(R.animal==a & R.window==w & R.category=="Rule2" & ismember(R.day,trainDays)), 'omitnan');
        if isfinite(r1) && isfinite(r2)
            deltas(ai) = r1 - r2;
        end
    end
    val = deltas(isfinite(deltas));
    p12 = NaN; med12 = NaN;
    if ~isempty(val)
        try
            p12 = signrank(val, 0);
        catch
            s = sum(val>0); nN = numel(val);
            p12 = 2*binocdf(min(s, nN-s), nN, 0.5);
        end
        med12 = median(val,'omitnan');
    end
    stats.(w).r1_vs_r2 = struct('n',numel(val),'median_delta',med12,'p',p12);

    %% (D) (Rule-pref avg) vs Non-rule (average across training days, per animal)
    deltas = nan(numel(animals),1);
    for ai = 1:numel(animals)
        a = animals(ai);
        r1 = mean(R.auc_mean(R.animal==a & R.window==w & R.category=="Rule1"   & ismember(R.day,trainDays)),'omitnan');
        r2 = mean(R.auc_mean(R.animal==a & R.window==w & R.category=="Rule2"   & ismember(R.day,trainDays)),'omitnan');
        nr = mean(R.auc_mean(R.animal==a & R.window==w & R.category=="NonRule"& ismember(R.day,trainDays)),'omitnan');
        rp = mean([r1 r2],'omitnan');
        if isfinite(rp) && isfinite(nr)
            deltas(ai) = rp - nr;
        end
    end
    val = deltas(isfinite(deltas));
    pRN = NaN; medRN = NaN;
    if ~isempty(val)
        try
            pRN = signrank(val, 0);
        catch
            s = sum(val>0); nN = numel(val);
            pRN = 2*binocdf(min(s, nN-s), nN, 0.5);
        end
        medRN = median(val,'omitnan');
    end
    stats.(w).rulepref_vs_nonrule = struct('n',numel(val),'median_delta',medRN,'p',pRN);
end
end

