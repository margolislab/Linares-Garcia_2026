            end
        end

        % --- title ---
        if isfinite(trendP)
            title(ax, sprintf('%s window (trend p=%.3g)', w, trendP));
        else
            title(ax, sprintf('%s window', w));
        end

        % --- your existing Five vs Reversal bracket (kept) ---
        idFive = find(strcmp(days,'Five')); idRev = find(strcmp(days,'Reversal'));
        if ~isempty(idFive) && ~isempty(idRev) && any(isfinite([y(idFive) y(idRev)]))
