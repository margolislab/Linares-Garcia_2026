function neuron_level_LME(ruleselsummary, days)
% Mixed-effects on per-neuron tuning STRENGTH (magnitude), not signed auROC.
% Windows: Sound/Early. Random intercept per animal.
% Prints:
%  - Training trend (One–Five): β and p on strength
%  - Five vs Reversal: Δstrength and p
%  - Rule-pref (Rule1|Rule2) vs Non-Rule during training: Δstrength and p

if exist('fitlme','file')~=2
    warning('fitlme not found; skipping neuron-level mixed-effects.');
    return;
end

S = ruleselsummary;
need = ismember({'animal','day','window','auROC'}, S.Properties.VariableNames);
if ~all(need)
    warning('Summary lacks required columns (animal/day/window/auROC).'); return;
end

% Keep finite auROC and target windows
S = S( (S.window=="Sound" | S.window=="Early") & isfinite(S.auROC), :);

% Build category from Part-1 if available
S.category = repmat("NonRule", height(S),1);
hasFDR  = ismember('sig_FDR',  S.Properties.VariableNames);
hasTask = ismember('sig_task', S.Properties.VariableNames);
if hasFDR
    S.category(S.sig_FDR & S.auROC>0.5) = "Rule1";
    S.category(S.sig_FDR & S.auROC<0.5) = "Rule2";
    if hasTask
        S.category(~S.sig_FDR & S.sig_task) = "NonRule";
    end
end

% Categorical coercion
S.animal = categorical(string(S.animal));
S.day    = categorical(string(S.day));
S.window = categorical(string(S.window));

% Day index 1..5
trainDaysStr = string(days);
trainDaysCat = categorical(trainDaysStr);
dmap = containers.Map(cellstr(trainDaysStr), 1:numel(trainDaysStr));
S.dayIndex = nan(height(S),1);
for i=1:height(S)
    k = char(string(S.day(i)));
    if isKey(dmap,k), S.dayIndex(i) = dmap(k); end
end

% ---- ALIGN & MAGNITUDE ----
S.aligned = S.auROC;                 % align Rule2 upward
isR2 = (S.category=="Rule2");
S.aligned(isR2) = 1 - S.aligned(isR2);
S.strength = abs(S.aligned - 0.5);   % 0..0.5, larger = stronger tuning

for w = ["Sound","Early"]
    Sw = S(S.window==categorical(w), :);

    % (i) Training trend (One–Five), All neurons (exclude Reversal)
    Tmask = Sw.day ~= categorical("Reversal") & ismember(Sw.day, trainDaysCat);
    T = Sw(Tmask, :);
    if height(T) >= 50 && all(isfinite(T.dayIndex))
        lme = fitlme(T, 'strength ~ 1 + dayIndex + (1|animal)');
        ct  = lme.Coefficients; r = strcmp(ct.Name,'dayIndex');
        if any(r)
            fprintf('[NEURON-LME MAG] %s — Trend (All strength): beta=%.4f, p=%.4g\n', ...
                char(w), ct.Estimate(r), ct.pValue(r));
        end
    end

    % (ii) Five vs Reversal (All neurons), on strength
    Fmask = ismember(Sw.day, categorical(["Five","Reversal"]));
    F = Sw(Fmask, :);
    if height(F) >= 30
        F.isReversal = double(F.day==categorical("Reversal"));
        lme = fitlme(F, 'strength ~ 1 + isReversal + (1|animal)');
        ct  = lme.Coefficients; r = strcmp(ct.Name,'isReversal');
        if any(r)
            fprintf('[NEURON-LME MAG] %s — Five vs Reversal (All strength): Δ=%.4f, p=%.4g\n', ...
                char(w), ct.Estimate(r), ct.pValue(r));
        end
    end

    % (iii) Rule-pref vs Non-rule during training, on strength
    Rmask = Sw.day ~= categorical("Reversal") & ismember(Sw.day, trainDaysCat) & ...
            ismember(Sw.category, ["Rule1","Rule2","NonRule"]);
    R = Sw(Rmask, :);
    if height(R) >= 30 && all(isfinite(R.dayIndex))
        R.RulePref = double(R.category=="Rule1" | R.category=="Rule2");
        lme = fitlme(R, 'strength ~ 1 + RulePref + dayIndex + (1|animal)');
        ct  = lme.Coefficients; r = strcmp(ct.Name,'RulePref_true');
        if ~any(r), r = strcmp(ct.Name,'RulePref'); end
        if any(r)
            fprintf('[NEURON-LME MAG] %s — Rule-pref vs Non-rule (strength): Δ=%.4f, p=%.4g\n', ...
                char(w), ct.Estimate(r), ct.pValue(r));
        end
    end
end
end

function h = fig_decoder_sound_vs_early_rulepref_nonrule(R, days)
% Plot decoder performance in the Sound and Early windows.
%
% Left panel:
%   Rule-preferring neurons, computed as the within-animal average of the
%   Rule1 and Rule2 category decoders.
%
% Right panel:
%   Non-rule task-modulated neurons.
%
% Each line connects the Sound-window and Early-window decoder AUC for one
% learning day. Paired statistics are computed across animals that have data
% in both windows.

if isempty(R) || height(R)==0
    h = figure('Name','Fig. 7E/I - Sound versus Early decoder AUC', ...
        'Position',[80 80 1100 480],'Visible','on');
    tiledlayout(1,2);
    nexttile; axis off; title('No decoder rows available');
    nexttile; axis off; title('No decoder rows available');
    return;
end

if ~isstring(R.animal),   R.animal   = string(R.animal);   end
if ~isstring(R.day),      R.day      = string(R.day);      end
if ~isstring(R.window),   R.window   = string(R.window);   end
if ~isstring(R.category), R.category = string(R.category); end

R = R(ismember(R.window, ["Sound","Early"]), :);

h = figure('Name','Fig. 7E/I - Sound versus Early decoder AUC', ...
    'Position',[80 80 1100 480], 'Visible','on');

tl = tiledlayout(1,2,'TileSpacing','compact','Padding','compact');
titles = ["Rule-preferring neurons", "Non-rule task-modulated neurons"];
colors = lines(max(3, numel(days)));

for panel = 1:2
    ax = nexttile(tl, panel);
    hold(ax, 'on');
    box(ax, 'on');
    set(ax, 'XLim', [0.7 2.3]);
    xticks(ax, [1 2]);
    xticklabels(ax, {'Sound','Early'});
    ylabel(ax, 'Decoder AUC');
    yline(ax, 0.5, 'k--');
    title(ax, titles(panel));

    yAll = [];
    legH = gobjects(0);
    legLbl = strings(0);

    for di = 1:numel(days)
        dayName = string(days{di});

        if panel == 1
            [soundVals, earlyVals] = per_animal_rulepref(R, dayName);
        else
            [soundVals, earlyVals] = per_animal_nonrule(R, dayName);
        end

        muSound = mean(soundVals, 'omitnan');
        semSound = sem(soundVals);
        muEarly = mean(earlyVals, 'omitnan');
        semEarly = sem(earlyVals);

        if ~isfinite(muSound) && ~isfinite(muEarly)
            continue;
        end

        yAll = [yAll; muSound; muEarly]; %#ok<AGROW>

        thisColor = colors(di, :);
        hLine = errorbar(ax, [1 2], [muSound muEarly], [semSound semEarly], ...
            'o-', 'LineWidth', 1.5, 'MarkerSize', 6, 'Color', thisColor);

        legH(end+1) = hLine; %#ok<AGROW>
        legLbl(end+1) = dayName; %#ok<AGROW>

        pairedMask = isfinite(soundVals) & isfinite(earlyVals);
        nPairs = sum(pairedMask);

        pSignrank = NaN;
        pPermutation = NaN;
        medianDelta = NaN;

        if nPairs >= 2
            deltaAUC = soundVals(pairedMask) - earlyVals(pairedMask);
            medianDelta = median(deltaAUC, 'omitnan');

            try
                pSignrank = signrank(soundVals(pairedMask), earlyVals(pairedMask), 'tail', 'right');
            catch
                pSignrank = NaN;
            end

            pPermutation = paired_perm_right(deltaAUC, 10000);
        end

        pPlot = min([pSignrank pPermutation], [], 'omitnan');

        if isfinite(pPlot) && pPlot < 0.10
            yTop = max([muSound + semSound, muEarly + semEarly], [], 'omitnan');
            if ~isfinite(yTop)
                yTop = max([muSound, muEarly], [], 'omitnan');
            end
            if ~isfinite(yTop)
                yTop = 0.6;
            end
            draw_bracket(ax, 1, 2, yTop + 0.02, sprintf('%s (n=%d)', p2stars_(pPlot), nPairs));
        end

        if nPairs >= 1
            fprintf('[Fig 7E/I] %s | %s: n=%d, median Sound-Early Δ=%.3f, p_signrank=%.3g, p_perm=%.3g\n', ...
                titles(panel), dayName, nPairs, medianDelta, pSignrank, pPermutation);
        end
    end

    if ~isempty(yAll) && any(isfinite(yAll))
        lo = min([0.45; yAll(isfinite(yAll))]) - 0.02;
        hi = max([0.90; yAll(isfinite(yAll))]) + 0.02;
        ylim(ax, [lo hi]);
    else
        ylim(ax, [0.45 0.95]);
    end

    grid(ax, 'on');

    if ~isempty(legH)
        legend(ax, legH, legLbl, 'Location', 'eastoutside');
    end
end

sgtitle(tl, 'Decoder AUC: Sound versus Early windows', 'FontWeight','bold');
end

function [sVals, eVals] = per_animal_rulepref(R, dayName)
% Returns per-animal AUC vectors for Sound and Early for RULE-PREF:
% (within animal) mean of R1 and R2 when available.
    Rday = R(R.day==dayName & ismember(R.category,["Rule1","Rule2"]), :);
    animals = unique(Rday.animal);
    sVals = nan(numel(animals),1); eVals = nan(numel(animals),1);

    for i=1:numel(animals)
        a = animals(i);
        % Sound
        v1s = extract_auc(Rday, a, dayName, "Sound", "Rule1");
        v2s = extract_auc(Rday, a, dayName, "Sound", "Rule2");
        sVals(i) = mean([v1s v2s],'omitnan');
        % Early
        v1e = extract_auc(Rday, a, dayName, "Early", "Rule1");
        v2e = extract_auc(Rday, a, dayName, "Early", "Rule2");
        eVals(i) = mean([v1e v2e],'omitnan');
    end
end

function [sVals, eVals] = per_animal_nonrule(R, dayName)
% Returns per-animal AUC vectors for Sound and Early for NON-RULE.
    Rday = R(R.day==dayName & R.category=="NonRule", :);
    animals = unique(Rday.animal);
    sVals = nan(numel(animals),1); eVals = nan(numel(animals),1);

    for i=1:numel(animals)
        a = animals(i);
        sVals(i) = extract_auc(Rday, a, dayName, "Sound", "NonRule");
        eVals(i) = extract_auc(Rday, a, dayName, "Early", "NonRule");
    end
end

function v = extract_auc(T, animalName, dayName, windowName, categoryName)
% Safe single-value extractor (returns NaN if missing).
    idx = T.animal==animalName & T.day==dayName & T.window==windowName & T.category==categoryName;
    if any(idx)
        v = T.auc_mean(find(idx,1,'first'));
    else
        v = NaN;
    end
end


function p = paired_perm_right(diffs, B)
% Right-tailed paired permutation test on within-subject differences.
% H1: mean(diff) > 0. Flips sign of each subject's diff with p=0.5.
    diffs = diffs(:);
    diffs = diffs(isfinite(diffs));
    n = numel(diffs);
    if n < 2 || all(diffs==0), p = NaN; return; end
    obs = mean(diffs,'omitnan');
    if ~isfinite(obs), p = NaN; return; end
    sgn = (rand(B, n) > 0.5)*2 - 1;   % B×n of ±1
    nullMean = mean(sgn .* diffs', 2, 'omitnan');  % (B×n .* 1×n)' => B×1
    p = mean(nullMean >= obs);
end