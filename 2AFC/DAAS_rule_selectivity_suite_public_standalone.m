function T = summarize_window_mix_counts(Summary, days)
% Per day, compute %Rule-pref (R1+R2) and %Non-rule for Sound vs Early,
% using ONLY neurons present in BOTH windows (same animal/day/neuron).
haveTask = ismember('sig_task', Summary.Properties.VariableNames);

rows = {};
for d = 1:numel(days)
    dayName = days{d};

    Ssound = Summary(strcmpi(Summary.window,'Sound') & strcmpi(Summary.day,dayName), :);
    Searly = Summary(strcmpi(Summary.window,'Early') & strcmpi(Summary.day,dayName), :);
    if isempty(Ssound) || isempty(Searly), continue; end

    % keys to intersect neurons within day
    keyS = Ssound.animal + "|" + Ssound.day + "|" + string(Ssound.neuron);
    keyE = Searly.animal + "|" + Searly.day + "|" + string(Searly.neuron);
    common = intersect(keyS, keyE);

    if isempty(common), continue; end
    inS = ismember(keyS, common);
    inE = ismember(keyE, common);
    Ssound = Ssound(inS,:); keyS = keyS(inS);
    Searly = Searly(inE,:); keyE = keyE(inE);

    % class masks
    ruleS = Ssound.sig_FDR;
    ruleE = Searly.sig_FDR;
    if haveTask
        nonS = Ssound.sig_task & ~Ssound.sig_FDR;
        nonE = Searly.sig_task & ~Searly.sig_FDR;
    else
        nonS = ~Ssound.sig_FDR;
        nonE = ~Searly.sig_FDR;
    end

    N = numel(common);
    rows(end+1,:) = { dayName, 'Rule',  100*sum(ruleE)/N, 100*sum(ruleS)/N, N }; %#ok<AGROW>
    rows(end+1,:) = { dayName, 'NonR',  100*sum(nonE)/N,  100*sum(nonS)/N,  N };
end

T = cell2table(rows, 'VariableNames', {'day','class','pct_Early','pct_Sound','Npaired'});
end

