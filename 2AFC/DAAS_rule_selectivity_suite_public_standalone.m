[T_sameHF, T_sameLF, ~] = scad_build_samecell_pairs( ...
    NewData2_DAAS, scadMinDays, stability_corr_type);

if saveTables
    writetable(T_pairNeur_all, fullfile(saveDir, 'source_Fig8G_crossday_category_pairs.csv'));
    writetable(T_sameHF, fullfile(saveDir, 'source_Fig8G_samecell_traceHF_pairs.csv'));
