function M = collect_mean_trace_rowwise(NewData2_DAAS, Ssub, modeStr, correctOnly, T)
% Row-wise mean ΔF/F when rows may belong to different days.
% modeStr: 'R1', 'R2', or 'BOTH'
if isempty(Ssub), M = []; return; end
C = cell(height(Ssub),1);

for i = 1:height(Ssub)
    A  = char(Ssub.animal(i));
    n  = Ssub.neuron(i);

    if ~ismember('day', Ssub.Properties.VariableNames) || isempty(Ssub.day(i))
        C{i} = []; continue;
    end
    dN = char(Ssub.day(i));
    if ~isfield(NewData2_DAAS,A) || ~isfield(NewData2_DAAS.(A),dN)
        C{i} = []; continue;
    end

    E = NewData2_DAAS.(A).(dN);
    if ~iscell(E) || n<1 || n>numel(E) || ~isfield(E{n},'data') || isempty(E{n}.data)
        C{i} = []; continue;
    end

    X = E{n}.data;                 % [nTrials x T']
    Tuse = min(size(X,2), T);

    [m1, m2] = get_correct_masks(E{n}, size(X,1), correctOnly);
    switch upper(modeStr)
        case 'R1',  use = m1;
        case 'R2',  use = m2;
        otherwise,  use = (m1 | m2);
    end
    if ~any(use), C{i} = []; continue; end

    % expand chained indexing into two steps
    Xc = X(1:numel(use), 1:Tuse);
    tr = mean(Xc(use, :), 1, 'omitnan');

    % pad/clip to T
    if numel(tr) < T, tr = [tr, nan(1, T-numel(tr))]; else, tr = tr(1:T); end
    C{i} = tr;
end

keep = ~cellfun(@isempty, C);
if ~any(keep), M = []; else, M = vertcat(C{keep}); end
end


