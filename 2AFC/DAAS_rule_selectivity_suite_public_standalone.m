function M = collect_mean_trace_pool(NewData2_DAAS, Ssub, dayName, rule1Only, correctOnly, T)
% Mean ΔF/F per neuron using ONLY correct trials for the requested rule.
% rule1Only==true -> use Rule1 correct trials; false -> Rule2 correct trials.
if isempty(Ssub), M = []; return; end
C = cell(height(Ssub),1);

for i = 1:height(Ssub)
    A  = char(Ssub.animal(i));
    n  = Ssub.neuron(i);
    if isempty(dayName) && ismember('day', Ssub.Properties.VariableNames)
        dN = char(Ssub.day(i));
    else
        dN = dayName;
    end
    if ~isfield(NewData2_DAAS,A) || ~isfield(NewData2_DAAS.(A),dN)
        C{i} = []; continue;
    end
    E = NewData2_DAAS.(A).(dN);
    if ~iscell(E) || n<1 || n>numel(E) || ~isfield(E{n},'data') || isempty(E{n}.data)
        C{i} = []; continue;
    end
    X = E{n}.data;  % [nTrials x T']
    Tuse = min(size(X,2), T);

    % Robust masks (vectors)
    [m1, m2] = get_correct_masks(E{n}, size(X,1), correctOnly);

    if rule1Only
        use = m1;
    else
        use = m2;
    end
    if ~any(use), C{i}=[]; continue; end

    X = X(:,1:Tuse);
    tr = mean(X(use,:), 1, 'omitnan');

    % pad/clip to T
    if numel(tr) < T, tr = [tr, nan(1, T-numel(tr))]; else, tr = tr(1:T); end
    C{i} = tr;
end

keep = ~cellfun(@isempty, C);
if ~any(keep), M = []; else, M = vertcat(C{keep}); end
end

function M = collect_mean_trace_pool_bothrules(NewData2_DAAS, Ssub, dayName, correctOnly, T)
% Mean ΔF/F using ALL correct trials (Rule1 OR Rule2) for each neuron in Ssub.
if isempty(Ssub), M = []; return; end
C = cell(height(Ssub),1);

for i = 1:height(Ssub)
    A  = char(Ssub.animal(i));
    n  = Ssub.neuron(i);

    % resolve day (explicit arg overrides table, else pull from table)
    if isempty(dayName) && ismember('day', Ssub.Properties.VariableNames)
        dN = char(Ssub.day(i));
    else
        dN = dayName;
    end
    if ~isfield(NewData2_DAAS,A) || ~isfield(NewData2_DAAS.(A),dN)
        C{i} = []; continue;
    end

    E = NewData2_DAAS.(A).(dN);
    if ~iscell(E) || n<1 || n>numel(E) || ~isfield(E{n},'data') || isempty(E{n}.data)
        C{i} = []; continue;
    end

    X = E{n}.data;                 % [nTrials x T']
    Tuse = min(size(X,2), T);

    [m1, m2] = get_correct_masks(E{n}, size(X,1), correctOnly);
    use = (m1 | m2);
    if ~any(use), C{i} = []; continue; end

    Xc = X(1:numel(use), 1:Tuse);
    tr = mean(Xc(use, :), 1, 'omitnan');

    if numel(tr) < T, tr = [tr, nan(1, T-numel(tr))]; else, tr = tr(1:T); end
    C{i} = tr;
end

keep = ~cellfun(@isempty, C);
if ~any(keep), M = []; else, M = vertcat(C{keep}); end
end


function [m1, m2] = get_correct_masks(En, nTrials, correctOnly)
% Return logical vectors m1 (Rule1-correct) and m2 (Rule2-correct) of length nTrials.
% If *_all fields exist and correctOnly==false, they will be used; otherwise rewarded-only masks.
m1 = false(nTrials,1); m2 = false(nTrials,1);

if ~isstruct(En) || ~isfield(En,'data') || isempty(En.data)
    return;
end

% Prefer *_all masks only if explicitly allowed and present
if ~correctOnly && isfield(En,'sound1Mask_all') && isfield(En,'sound2Mask_all') ...
               && ~isempty(En.sound1Mask_all)   && ~isempty(En.sound2Mask_all)
    m1v = logical(En.sound1Mask_all(:));
    m2v = logical(En.sound2Mask_all(:));
else
    if isfield(En,'sound1Mask') && ~isempty(En.sound1Mask)
        m1v = logical(En.sound1Mask(:));
    else
        m1v = false(nTrials,1);
    end
    if isfield(En,'sound2Mask') && ~isempty(En.sound2Mask)
        m2v = logical(En.sound2Mask(:));
    else
        m2v = false(nTrials,1);
    end
end

% Align sizes
nUse = min([nTrials, numel(m1v), numel(m2v)]);
m1(1:nUse) = m1v(1:nUse);
m2(1:nUse) = m2v(1:nUse);
end

