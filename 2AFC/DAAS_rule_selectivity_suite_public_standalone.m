function NewData2_DAAS = integrate_scad_tables_if_requested(NewData2_DAAS, scadCSVMap, days, T, correctOnly)
% Add same-cell-across-days registration tables if CSV paths were provided.

if isempty(scadCSVMap) || ~isstruct(scadCSVMap)
    return;
end

animalNames = fieldnames(NewData2_DAAS);

for ai = 1:numel(animalNames)
    animalName = animalNames{ai};

    if isfield(scadCSVMap, animalName) && ~isempty(scadCSVMap.(animalName))
        if ~isfield(NewData2_DAAS.(animalName), 'SCAD') || ...
                ~isfield(NewData2_DAAS.(animalName).SCAD, 'table')

            fprintf('[DAAS public] Building SCAD table for %s from %s\n', ...
                animalName, scadCSVMap.(animalName));

            NewData2_DAAS.(animalName).SCAD.table = scad_table_from_csv( ...
                NewData2_DAAS.(animalName), scadCSVMap.(animalName), days, T, correctOnly);
        end
    end
end
end

function Sfix = export_sound_summary_for_figures(Summary, saveDir)
% Standardize the sound-window summary used for downstream category figures.

S = Summary;

vn = lower(string(S.Properties.VariableNames));
findcol = @(cands) find(ismember(vn, lower(string(cands))), 1, 'first');

c_animal  = findcol({'animal'});
c_day     = findcol({'day'});
c_window  = findcol({'window','win','phase'});
c_neuron  = findcol({'neuron','cell_idx','cell','roi','roi_idx'});
c_sigfdr  = findcol({'sig_fdr','sigfdr','sig_rule_fdr','sig'});
c_auroc   = findcol({'auroc','rule_auroc','auroc_sound','roc'});
c_sigtask = findcol({'sig_task','sigtask','task_sig','sig_any_task'});

requiredNames = {'animal','day','window','neuron','sig_FDR','auROC'};
missing = requiredNames([isempty(c_animal), isempty(c_day), isempty(c_window), ...
    isempty(c_neuron), isempty(c_sigfdr), isempty(c_auroc)]);

if ~isempty(missing)
    error('Cannot export standardized summary. Missing columns: %s.', strjoin(missing, ', '));
end

Sfix = table();
Sfix.animal = string(S{:, c_animal});
Sfix.day    = string(S{:, c_day});
Sfix.window = string(S{:, c_window});

neuronRaw = S{:, c_neuron};
if iscell(neuronRaw)
    neuronRaw = cellfun(@double, neuronRaw);
end

Sfix.neuron  = double(neuronRaw);
Sfix.sig_FDR = logical(S{:, c_sigfdr});
Sfix.auROC   = double(S{:, c_auroc});

if isempty(c_sigtask)
    Sfix.sig_task = false(height(Sfix), 1);
else
    Sfix.sig_task = logical(S{:, c_sigtask});
end

Sfix = Sfix(Sfix.window == "Sound", :);

[~, iu] = unique(Sfix(:, {'animal','day','window','neuron'}), 'stable');
Sfix = Sfix(iu, :);

if ~isempty(saveDir)
    writetable(Sfix, fullfile(saveDir, 'source_sound_rule_summary_for_figures.csv'));
end
end

