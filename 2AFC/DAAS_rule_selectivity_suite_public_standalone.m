        'FontWeight','bold','FontSize',10);

    else
        fprintf('[%s | category composition across days (excl Reversal)] Not enough non-Reversal days with data for chi-square.\n', Wname);
    end

    % Per-category Day5 vs Reversal p-values (Fisher exact)
    sR1='n.s.'; sR2='n.s.'; sNR='n.s.';
    if ~isempty(idxFive) && ~isempty(idxRev) && isfinite(TOT(idxFive)) && isfinite(TOT(idxRev)) && ...
            TOT(idxFive)>0 && TOT(idxRev)>0

        pR1 = fisher_2x2_p(R1(idxFive), TOT(idxFive)-R1(idxFive), R1(idxRev), TOT(idxRev)-R1(idxRev));
        pR2 = fisher_2x2_p(R2(idxFive), TOT(idxFive)-R2(idxFive), R2(idxRev), TOT(idxRev)-R2(idxRev));
        pNR = fisher_2x2_p(NR(idxFive), TOT(idxFive)-NR(idxFive), NR(idxRev), TOT(idxRev)-NR(idxRev));

        sR1 = p_to_stars(pR1); sR2 = p_to_stars(pR2); sNR = p_to_stars(pNR);

        if all(isfinite(P(idxFive,:)))
            text(ax3, idxFive, 103, sprintf('R1:%s  R2:%s  NR:%s', sR1, sR2, sNR), ...
                'HorizontalAlignment','center','FontSize',10,'FontWeight','bold');
        end
        if all(isfinite(P(idxRev,:)))
            text(ax3, idxRev, 103, sprintf('R1:%s  R2:%s  NR:%s', sR1, sR2, sNR), ...
                'HorizontalAlignment','center','FontSize',10,'FontWeight','bold');
        end
    end

    % -------- Console summary (concise) --------
    fprintf('--- STATS (%s) ---\n', Wname);
    fprintf('%% Modulated trend across days (Spearman rho): rho=%.3f, p=%g\n', rho_mod, p_trend_mod);

    if ~isnan(p_5vR_mod)
        fprintf('Day Five vs Reversal (%% Modulated): p=%g   [Five: %d/%d, Reversal: %d/%d]\n', ...
            p_5vR_mod, counts_mod(idxFive), totals_mod(idxFive), counts_mod(idxRev), totals_mod(idxRev));
    end

    if ~isempty(idxFive) && ~isempty(idxRev) && isfinite(TOT(idxFive)) && isfinite(TOT(idxRev)) && TOT(idxFive)>0 && TOT(idxRev)>0
        fprintf('Day Five vs Reversal (categories):  R1 p=%g, R2 p=%g, Non-rule p=%g\n', ...
            fisher_2x2_p(R1(idxFive), TOT(idxFive)-R1(idxFive), R1(idxRev), TOT(idxRev)-R1(idxRev)), ...
            fisher_2x2_p(R2(idxFive), TOT(idxFive)-R2(idxFive), R2(idxRev), TOT(idxRev)-R2(idxRev)), ...
            fisher_2x2_p(NR(idxFive), TOT(idxFive)-NR(idxFive), NR(idxRev), TOT(idxRev)-NR(idxRev)) );
    end

end
