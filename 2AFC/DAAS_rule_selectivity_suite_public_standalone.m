function r = safe_corr(a,b,corrType)
% a,b: vectors; corrType: 'Spearman' or 'Pearson'
a = a(:); b = b(:);
n = min(numel(a), numel(b));
a = a(1:n); b = b(1:n);
try
    % single-output only
    r = corr(a,b,'type',corrType,'rows','pairwise');
catch
    R = corrcoef(a,b,'Rows','pairwise');
    r = R(1,2);
end
if isnan(r), r = 0; end
end

