function edges = estimate_corrdist_edges(NewData2_DAAS, Summary, days, dayList)
% Build wide-enough bins from actual coords on the selected days.
maxD = 0;
Ssound = Summary(strcmpi(Summary.window,'Sound'),:);
animals = unique(Ssound.animal);
for ai=1:numel(animals)
    A = char(animals(ai));
    for di=1:numel(dayList)
        D = dayList{di};
        if ~ismember(D, days), continue; end
        if ~isfield(NewData2_DAAS, A) || ~isfield(NewData2_DAAS.(A), D), continue; end
        E = NewData2_DAAS.(A).(D);
        C = nan(numel(E),2);
        for n=1:numel(E)
            if isfield(E{n},'coord_xy') && numel(E{n}.coord_xy)>=2 && all(isfinite(E{n}.coord_xy(1:2)))
                C(n,:) = double(E{n}.coord_xy(1:2));
            end
        end
        C = C(all(isfinite(C),2),:);
        if size(C,1) >= 2
            % rough upper bound = diagonal of bbox
            mn = min(C,[],1); mx = max(C,[],1);
            maxD = max(maxD, hypot(mx(1)-mn(1), mx(2)-mn(2)));
        end
    end
end
if maxD<=0, maxD = 500; end           % safe fallback
nBins = max(8, min(20, ceil(maxD/60)));% 8–20 bins
edges = linspace(0, ceil(maxD/10)*10, nBins+1);
end

    function c = getCoordSafe(En)
c = [NaN NaN];
if isstruct(En) && isfield(En,'coord_xy') && numel(En.coord_xy)>=2
    v = double(En.coord_xy(1:2));
    if all(isfinite(v)), c = v; end
end
end


function [T_pairs] = corrdist_collect_pairs_from_soundcats(NewData2_DAAS, Summary, days, Wsound, Wearly, minTrials, corrType, dayList, maxPairsPerAnimal, minDistPx)
% Collect raw pair-level (distance, r) for Sound-categorized neurons.
% Returns a table with columns: animal, day, winResp, category, dist, r

if nargin<9 || isempty(dayList), dayList = {'Five'}; end
if nargin<10 || isempty(maxPairsPerAnimal), maxPairsPerAnimal = 50000; end
if nargin<11 || isempty(minDistPx), minDistPx = 0; end

haveTask = ismember('sig_task', Summary.Properties.VariableNames);
Ssound   = Summary(strcmpi(Summary.window,'Sound'),:);
animals  = unique(Ssound.animal);

cats        = {'Rule1','Rule2','Non-rule'};
winRespList = {'Sound','Early'};

rows = {};
for ai = 1:numel(animals)
    A = char(animals(ai));
    for di = 1:numel(dayList)
        D = dayList{di};
        if ~ismember(D, days), continue; end
        if ~isfield(NewData2_DAAS, A) || ~isfield(NewData2_DAAS.(A), D), continue; end

        Sd = Ssound(strcmpi(Ssound.animal,animals(ai)) & strcmpi(Ssound.day,D), :);
        if isempty(Sd), continue; end

        idx_R1 = Sd.sig_FDR & strcmpi(Sd.pref,'Rule1');
        idx_R2 = Sd.sig_FDR & strcmpi(Sd.pref,'Rule2');
        if haveTask, idx_NR = Sd.sig_task & ~Sd.sig_FDR; else, idx_NR = ~Sd.sig_FDR; end

        Neurons.R1 = double(Sd.neuron(idx_R1));
        Neurons.R2 = double(Sd.neuron(idx_R2));
        Neurons.NR = double(Sd.neuron(idx_NR));
        if isempty(Neurons.R1) && isempty(Neurons.R2) && isempty(Neurons.NR), continue; end

        for wr = 1:numel(winRespList)
            winResp = winRespList{wr};
            switch winResp
                case 'Sound', W = Wsound;
                case 'Early', W = Wearly;
                otherwise,    W = Wsound;
            end
            if isempty(W), continue; end

            for c = 1:numel(cats)
                catName = cats{c};
                switch catName
                    case 'Rule1', listN = Neurons.R1; subsetTag = 'R1';
                    case 'Rule2', listN = Neurons.R2; subsetTag = 'R2';
                    otherwise,    listN = Neurons.NR; subsetTag = 'BOTH';
                end
                if numel(listN) < 2, continue; end

                [distVals, rVals] = corrdist_pairs_for_set(NewData2_DAAS.(A).(D), listN, W, subsetTag, minTrials, corrType);
