function [ruleLbl, fromIdx] = get_rule_labels(E, correctOnly)
% GET_RULE_LABELS
% Return a trial-length vector with values:
%   1 -> Rule 1 (S1),  2 -> Rule 2 (S2),  NaN -> not labeled
ruleLbl = [];
fromIdx = [];

persistent warnedFallback
if isempty(warnedFallback), warnedFallback = false; end
if isempty(E) || ~iscell(E), return; end

for n = 1:numel(E)
    en = E{n};
    if ~isstruct(en) || ~isfield(en,'data') || isempty(en.data), continue; end
    useAll = ~correctOnly && isfield(en,'sound1Mask_all') && isfield(en,'sound2Mask_all');

    if useAll
        s1 = logical(en.sound1Mask_all);
        s2 = logical(en.sound2Mask_all);
    elseif isfield(en,'sound1Mask') && isfield(en,'sound2Mask')
        s1 = logical(en.sound1Mask);
        s2 = logical(en.sound2Mask);
        if ~correctOnly && ~warnedFallback
            warnedFallback = true;
            warning('%s', sprintf(['get_rule_labels: *_all masks not found; ', ...
                                   'falling back to rewarded-only masks (sound1Mask/sound2Mask).']));
        end
    else
        continue;
    end

    L = nan(size(s1));
    L(s1) = 1; L(s2) = 2;
    both = s1 & s2; if any(both), L(both) = 1; end
    ruleLbl = L(:); fromIdx = n; return;
end
end

function [Feat, ok] = collect_features(E, idxMaskEntry, keep, W)
% Per neuron: mean ΔF/F across frames W, for the selected trials (keep)
N = numel(E);
Feat = cell(N,1);
ok   = false(N,1);
for n = 1:N
    if ~isstruct(E{n}) || ~isfield(E{n},'data') || isempty(E{n}.data), continue; end
    X = E{n}.data;           % [nTrials x T]
    if isempty(X) || size(X,2) < max(W), continue; end
    % match trial count with rule label vector source
    if size(X,1) ~= size(E{idxMaskEntry}.data,1)
        Nt = min(size(X,1), size(E{idxMaskEntry}.data,1));
        X  = X(1:Nt, :);
        k2 = find(keep); k2 = k2(k2<=Nt);
        K  = false(Nt,1); K(k2) = true;
    else
        K = keep;
    end
    if ~any(K), continue; end
    v = mean(X(:, W), 2);    % feature per trial
    Feat{n} = v(K);
    ok(n)   = true;
end
end

function a = auc_2sample(x, y)
% Mann-Whitney U based AUROC (no toolbox)
x = x(isfinite(x)); y = y(isfinite(y));
nx = numel(x); ny = numel(y);
if nx==0 || ny==0, a = NaN; return; end
v = [x(:); y(:)];
r = tiedrank(v);           % average ranks for ties
rx = r(1:nx);
U  = sum(rx) - nx*(nx+1)/2;
a  = U / (nx*ny);
end

function p = perm_p_auroc(x, lbl, nPerm)
% Two-tailed permutation p for auROC (Rule1 vs Rule2)
x   = x(:);
lbl = lbl(:);          % 1 or 2
ix1 = find(lbl==1);
ix2 = find(lbl==2);
if numel(ix1)==0 || numel(ix2)==0, p = NaN; return; end
obs = auc_2sample(x(ix1), x(ix2));
if ~isfinite(obs), p = NaN; return; end
n   = numel(lbl);
permVals = zeros(nPerm,1);
for k=1:nPerm
    shuf = lbl(randperm(n));
    s1 = find(shuf==1); s2 = find(shuf==2);
    permVals(k) = auc_2sample(x(s1), x(s2));
end
p = mean( abs(permVals - 0.5) >= abs(obs - 0.5) );
end

function p = perm_p_paired(winVals, baseVals, nPerm)
% Two-tailed paired permutation (sign-flip) test on per-trial differences
d = winVals(:) - baseVals(:);
d = d(isfinite(d));
if isempty(d), p = NaN; return; end
obs = mean(d);
n   = numel(d);
permMeans = zeros(nPerm,1);
for k=1:nPerm
    sgn = (rand(n,1) > 0.5)*2 - 1;   % ±1
    permMeans(k) = mean(d .* sgn);
end
p = mean(abs(permMeans) >= abs(obs));
end

function thr = fdr_threshold(p, q, method)
% Single BH threshold
p = p(:); p = p(isfinite(p));
if isempty(p), thr = q; return; end
switch lower(method)
    case 'bh'
        [ps,~] = sort(p);
        m = numel(ps);
        k = find(ps <= ((1:m)'/m)*q, 1, 'last');
        if isempty(k), thr = 0; else, thr = ps(k); end
    otherwise
        thr = q;
end
end

function s = p_to_stars(p)
if ~isfinite(p) || isnan(p)
    s = 'n.s.';
elseif p < 1e-3
    s = '***';
elseif p < 1e-2
    s = '**';
elseif p < 0.05
    s = '*';
else
    s = 'n.s.';
end
end

function [rho,p] = safe_corr_spearman(x,y)
% Spearman rho with NaN safety and small-n guard
x = x(:); y = y(:);
ok = isfinite(x) & isfinite(y);
x = x(ok); y = y(ok);
rho = NaN; p = NaN;
if numel(x) >= 3 && numel(unique(x)) > 1 && numel(unique(y)) > 1
    try
        [rho,p] = corr(x,y,'Type','Spearman');
    catch
        rho = NaN; p = NaN;
    end
end
end

function p = fisher_2x2_p(a,b,c,d)
% Two-sided Fisher exact p-value for a 2x2 table [[a b];[c d]]
if any([a b c d] < 0) || any(~isfinite([a b c d]))
    p = NaN; return;
end
row1 = a + b; row2 = c + d; col1 = a + c; col2 = b + d; n = row1 + row2;
if any([row1,row2,col1,col2]==0), p = 1; return; end

% Hypergeometric probability of observing x in [max(0,col1-row2) .. min(col1,row1)]
xmin = max(0, col1 - row2);
xmax = min(col1, row1);

% observed probability
p_obs = hypergeom_prob(a, row1, col1, n);

% two-sided p: sum of probabilities <= p_obs
p = 0;
for x = xmin:xmax
    px = hypergeom_prob(x, row1, col1, n);
    if px <= p_obs + eps, p = p + px; end
end
p = min(1, p);
end

function px = hypergeom_prob(x, row1, col1, n)
% P(X=x) for Fisher's exact test with fixed margins
% equals [C(col1,x) * C(n-col1, row1-x)] / C(n, row1)
px = exp( lognchoosek(col1, x) + lognchoosek(n-col1, row1-x) - lognchoosek(n, row1) );
end

function y = lognchoosek(n,k)
% stable log(n choose k)
if k < 0 || k > n, y = -Inf; return; end
y = gammaln(n+1) - gammaln(k+1) - gammaln(n-k+1);
end

function p = perm_2sample_p(x, y, nPerm)
% Two-sided permutation test on means (robust to NaNs)
x = x(isfinite(x)); y = y(isfinite(y));
nx = numel(x); ny = numel(y);
if nx==0 || ny==0, p = NaN; return; end
obs = abs(mean(x) - mean(y));
z = [x(:); y(:)];
n = numel(z);
cnt = 0;
for i=1:nPerm
    idx = randperm(n);
    x_ = z(idx(1:nx));
    y_ = z(idx(nx+1:end));
    if abs(mean(x_) - mean(y_)) >= obs, cnt = cnt + 1; end
end
p = cnt / nPerm;
end


