function T_stats = pairwise_ranksum_stats(groupNames, groupData)
% Pairwise nonparametric comparisons between plotted groups.
%
% These statistics are saved as source information for the figure. They are
% not required to draw the figure but help document how statistical labels
% or manuscript-reported comparisons were obtained.

valid = find(strlength(groupNames) > 0 & ~cellfun(@isempty, groupData));

if numel(valid) < 2
    T_stats = table();
    return;
end

pairs = nchoosek(valid, 2);
rawP = nan(size(pairs, 1), 1);
qVal = nan(size(pairs, 1), 1);
n1 = nan(size(pairs, 1), 1);
n2 = nan(size(pairs, 1), 1);
medianDiff = nan(size(pairs, 1), 1);

for k = 1:size(pairs, 1)
    i = pairs(k, 1);
    j = pairs(k, 2);

    x = finite_vector(groupData{i});
    y = finite_vector(groupData{j});

    n1(k) = numel(x);
    n2(k) = numel(y);

    if numel(x) >= 2 && numel(y) >= 2
        rawP(k) = ranksum(x, y);
        medianDiff(k) = median(x, 'omitnan') - median(y, 'omitnan');
    end
end

qVal = local_bh_fdr(rawP);

T_stats = table( ...
    groupNames(pairs(:, 1))', groupNames(pairs(:, 2))', ...
    n1, n2, medianDiff, rawP, qVal, ...
    'VariableNames', {'group_1','group_2','n_1','n_2','median_difference','p_value','q_value'});
end

function v = finite_vector(v)
% Return a column vector with only finite numeric values.

v = v(:);
v = v(isfinite(v));
end

function q = local_bh_fdr(p)
% Benjamini-Hochberg FDR correction.

q = nan(size(p));
valid = isfinite(p);

if ~any(valid)
    return;
end

pValid = p(valid);
[pSorted, order] = sort(pValid(:));
m = numel(pSorted);

qSorted = pSorted .* (m ./ (1:m))';
for i = m-1:-1:1
    qSorted(i) = min(qSorted(i), qSorted(i + 1));
end

qValid = nan(size(pValid));
qValid(order) = min(qSorted, 1);
q(valid) = qValid;
end

