    p_5vR_mod = NaN; stars_mod = 'n.s.';

    if ~isempty(idxFive) && ~isempty(idxRev) && ...
            isfinite(totals_mod(idxFive)) && isfinite(totals_mod(idxRev)) && ...
            totals_mod(idxFive)>0 && totals_mod(idxRev)>0

        a = counts_mod(idxFive); b = totals_mod(idxFive)-a;
