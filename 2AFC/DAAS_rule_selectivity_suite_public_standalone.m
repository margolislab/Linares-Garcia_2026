function DAAS_rule_selectivity_suite_public_standalone(NewData2_DAAS, params)
% DAAS_RULE_SELECTIVITY_SUITE_PUBLIC
%
% Public manuscript-figure version of the DAAS rule-selectivity analysis.
%
% This function reproduces the manuscript figure panels that use rule
% selectivity, pathway composition, spatial correlation-distance structure,
% and cross-day stability analyses from processed trial-wise calcium traces.
%
% The function intentionally excludes exploratory figures and debugging
% branches that were useful during analysis development but are not part of
% the final manuscript. It keeps intermediate tables only when they are
% required to generate a manuscript figure or to provide source data for that
% figure.
%
% -------------------------------------------------------------------------
% Manuscript outputs generated by this function
% -------------------------------------------------------------------------
%   Fig. 7A
%       Pooled heatmap of rule-selective activity.
%
%   Fig. 7B / Fig. 7F
%       Pooled 2 x 3 summary of rule-selective neurons.
%
%   Supplementary Fig. 5B
%       Per-day heatmap grid of rule-selective activity.
%
%   Supplementary Fig. 5G
%       Pathway composition comparison between Rule 1 and Rule 2 neurons.
%
%   Supplementary Fig. 5H
%       Pathway composition slope across days.
%
%   Supplementary Fig. 7C / Supplementary Fig. 7G
%       Sound-window versus early-post-sound category composition.
%
%   Fig. 8E
%       Pairwise response-correlation versus spatial-distance scatter plot.
%
%   Fig. 8F
%       Correlation-distance effect size across learning days.
%
%   Fig. 8G
%       Cross-day stability comparison between rule categories and same-cell
%       matched traces.
%
% -------------------------------------------------------------------------
% Expected input
% -------------------------------------------------------------------------
%   NewData2_DAAS
%       Processed data structure organized as:
%           NewData2_DAAS.(Animal).(Day){neuron}
%
%       Each neuron entry is expected to contain:
%           .data        [nTrials x nFrames] trial-wise calcium activity
%           .sound1Mask  logical vector for correct Rule 1 / Sound 1 trials
%           .sound2Mask  logical vector for correct Rule 2 / Sound 2 trials
%
%       Optional fields:
%           .neuronType  pathway/cell-type label, for example:
%                        'Identified D1', 'Identified A2a',
%                        'Putative D1', or 'Putative A2a'
%
%   params
%       Analysis parameter structure. Required and commonly used fields:
%
%           params.days
%               Cell array of day labels, for example:
%               {'One','Two','Three','Four','Five'}
%
%           params.nFrames
%               Number of imaging frames per aligned trial.
%
%           params.fs
%               Imaging sampling rate in Hz.
%
%           params.win.sound
%               Frame indices defining the sound-response window.
%
%           params.rule.save_dir
%               Output directory for manuscript figures and source tables.
%
%           params.rule.nPerm
%               Number of permutations for rule-selectivity tests.
%
%           params.rule.minTrialsPerRule
%               Minimum number of trials required for each rule.
%
%           params.rule.correct_only
%               Whether to use correct trials only.
%
% Notes:
%   This public function assumes that the helper functions used in the
%   original analysis pipeline are available on the MATLAB path. Examples
%   include collect_features, auc_2sample, perm_p_auroc,
%   fig_rule_pooled_2x3, corrdist_build_tables_from_soundcats, and related
%   plotting/statistics helpers.

%% ------------------------------------------------------------------------
% 1. Read parameters and set defaults
% -------------------------------------------------------------------------

if nargin < 2
    params = struct();
end

days = getf(params, 'days', []);
if isempty(days)
    error('params.days is required, for example: {''One'',''Two'',''Three'',''Four'',''Five''}.');
end

T      = getf(params, 'nFrames', 89);
fs     = getf(params, 'fs', 16);
Wsound = getf(getf(params, 'win', struct()), 'sound', 32:40);

rule = getf(params, 'rule', struct());

% Core rule-selectivity settings.
nPerm       = getf(rule, 'nPerm', 1000);
minTr       = getf(rule, 'minTrialsPerRule', 8);
early_s     = getf(rule, 'early_len_s', 0.5);
correctOnly = getf(rule, 'correct_only', true);

% Output settings.
saveDir    = getf(rule, 'save_dir', fullfile(pwd, 'rule_selectivity_public'));
saveFigs   = getf(rule, 'save_figs', true);
saveTables = getf(rule, 'save_tables', true);
closeFigs  = getf(rule, 'close_figs', false);
figFormats = getf(rule, 'fig_formats', {'png'});

if ischar(figFormats) || isstring(figFormats)
    figFormats = cellstr(figFormats);
end

if ~exist(saveDir, 'dir')
    mkdir(saveDir);
end

% Spatial correlation-distance settings used for Fig. 8E/F.
corrEdges     = getf(rule, 'corrdist_edges', 0:25:400);
px_um         = getf(rule, 'px_um', NaN);
corrDays      = getf(rule, 'corrdist_days', {'Four'});
corrMinTrials = getf(rule, 'corrdist_minTrials', 8);
corrType      = getf(rule, 'corrdist_type', 'Spearman');
corrEqualWt   = getf(rule, 'corrdist_equal_weight_animals', true);
corrFit       = getf(rule, 'corrdist_fit', 'linear');
corrMaxPairs  = getf(rule, 'corrdist_max_pairs', 50000);
corrMinDistPx = getf(rule, 'corrdist_min_px', 5);

% Cross-day stability settings used for Fig. 8G.
stabilityExcludeDays         = getf(rule, 'stability_exclude_days', {'Reversal'});
stability_minTrialsPerNeuron = getf(rule, 'stability_minTrialsPerNeuron', 6);
stability_corr_type          = getf(rule, 'stability_corr_type', 'Pearson');

% Same-cell-across-days settings used for Fig. 8G.
scadCSVMap  = getf(rule, 'scad_csvs', struct());
scadMinDays = getf(rule, 'scad_min_days', 2);

% Derive the early post-sound and baseline windows from the sound window.
tone_on  = min(Wsound);
tone_off = max(Wsound);
Wearly   = tone_off + 1 : min(tone_off + round(early_s * fs), T);

pre_len = round(0.5 * fs);
Wbase   = max(1, tone_on - pre_len) : max(1, tone_on - 1);

fprintf('\n[DAAS public] Sound window: frames %d-%d\n', min(Wsound), max(Wsound));
fprintf('[DAAS public] Early window: frames %d-%d\n', min(Wearly), max(Wearly));
fprintf('[DAAS public] Baseline window: frames %d-%d\n', min(Wbase), max(Wbase));
fprintf('[DAAS public] Output directory: %s\n\n', saveDir);

%% ------------------------------------------------------------------------
% 2. Optional same-cell metadata integration
% -------------------------------------------------------------------------
% Some cross-day stability analyses require same-cell registration metadata.
% If SCAD CSV paths are provided in params.rule.scad_csvs, they are converted
% into NewData2_DAAS.(Animal).SCAD.table before the stability figure is made.

NewData2_DAAS = integrate_scad_tables_if_requested( ...
    NewData2_DAAS, scadCSVMap, days, T, correctOnly);

%% ------------------------------------------------------------------------
% 3. Compute per-neuron rule selectivity
% -------------------------------------------------------------------------
% For each animal, day, and analysis window, the code computes:
%   1) auROC between Rule 1 and Rule 2 trials;
%   2) permutation p-value for rule selectivity;
%   3) FDR-corrected rule-selective classification;
%   4) baseline-versus-window task modulation.

animals = fieldnames(NewData2_DAAS);

Summary = table('Size', [0 10], ...
    'VariableTypes', {'string','string','double','string','double','double','logical','string','string','logical'}, ...
    'VariableNames', {'animal','day','neuron','window','auROC','p_perm','sig_FDR','pref','pathway','sig_task'});

windows = {'Sound', 'Early'};
Wbins   = {clipW(Wsound, T), clipW(Wearly, T)};

for ai = 1:numel(animals)
    animalName = animals{ai};

    % Ignore non-animal fields, such as shared metadata, if present.
    if ~isstruct(NewData2_DAAS.(animalName))
        continue;
    end

    for di = 1:numel(days)
        dayName = days{di};

        if ~isfield(NewData2_DAAS.(animalName), dayName) || isempty(NewData2_DAAS.(animalName).(dayName))
            fprintf('[DAAS public] Skipping %s / %s: no data found.\n', animalName, dayName);
            continue;
        end

        E = NewData2_DAAS.(animalName).(dayName);
        N = numel(E);

        [ruleLbl, useIdx] = get_rule_labels(E, correctOnly);

        if isempty(ruleLbl)
            fprintf('[DAAS public] Skipping %s / %s: no usable rule labels.\n', animalName, dayName);
            continue;
        end

        keep = ruleLbl == 1 | ruleLbl == 2;
        ruleLbl = ruleLbl(keep);

        for wi = 1:numel(windows)
            windowName = windows{wi};
            Wv = Wbins{wi};

            if isempty(Wv)
                fprintf('[DAAS public] Skipping %s / %s / %s: empty window.\n', animalName, dayName, windowName);
                continue;
            end

            [Feat, okNeuron] = collect_features(E, useIdx, keep, Wv);
            [Base, okBase]   = collect_features(E, useIdx, keep, Wbase);

            if isempty(Feat)
                fprintf('[DAAS public] Skipping %s / %s / %s: no features extracted.\n', animalName, dayName, windowName);
                continue;
            end

            nR1 = sum(ruleLbl == 1);
            nR2 = sum(ruleLbl == 2);

            if nR1 < minTr || nR2 < minTr
                fprintf('[DAAS public] Skipping %s / %s / %s: too few trials (Rule1=%d, Rule2=%d).\n', ...
                    animalName, dayName, windowName, nR1, nR2);
                continue;
            end

            au = nan(N, 1);
            pp = nan(N, 1);

            for n = 1:N
                if ~okNeuron(n)
                    continue;
                end

                x = Feat{n};
                if all(~isfinite(x))
                    continue;
                end

                r1 = x(ruleLbl == 1);
                r2 = x(ruleLbl == 2);

                if isempty(r1) || isempty(r2)
                    continue;
                end

                au(n) = auc_2sample(r1, r2);
                pp(n) = perm_p_auroc(x, ruleLbl, nPerm);
            end

            thrRule = fdr_threshold(pp, 0.05, 'bh');
            sigRule = pp <= thrRule;

            p_task = nan(N, 1);
            for n = 1:N
                if ~okNeuron(n) || ~okBase(n)
                    continue;
                end

                xw = Feat{n};
                xb = Base{n};

                if numel(xw) ~= numel(xb)
                    continue;
                end

                p_task(n) = perm_p_paired(xw, xb, nPerm);
            end

            thrTask = fdr_threshold(p_task, 0.05, 'bh');
            sigTask = p_task <= thrTask;

            pref = strings(N, 1);
            pref(au > 0.5)  = "Rule1";
            pref(au < 0.5)  = "Rule2";
            pref(au == 0.5) = "Tie";

            Ttab = table((1:N)', au, pp, sigRule, pref, repmat(string(windowName), N, 1), ...
                p_task, sigTask, ...
                'VariableNames', {'neuron','auROC','p_perm','sig_FDR','pref','window','p_task','sig_task'});

            Ttab.animal = repmat(string(animalName), N, 1);
            Ttab.day    = repmat(string(dayName), N, 1);
            Ttab.pathway = strings(N, 1);

            for n = 1:N
                if isfield(E{n}, 'neuronType') && ~isempty(E{n}.neuronType)
                    Ttab.pathway(n) = string(E{n}.neuronType);
                end
            end

            if saveTables
                outTable = fullfile(saveDir, sprintf('source_rule_selectivity_%s_%s_%s.csv', ...
                    animalName, dayName, windowName));
                writetable(Ttab, outTable);
            end

            Summary = append_window(Summary, animalName, dayName, windowName, au, pp, sigRule, sigTask, E);
        end
    end
end

if isempty(Summary)
    error('No rule-selectivity results were generated. Check the input data structure and params.days.');
end

if saveTables
    writetable(Summary, fullfile(saveDir, 'source_rule_selectivity_summary_all_windows.csv'));
    Sfix = export_sound_summary_for_figures(Summary, saveDir);
else
    Sfix = export_sound_summary_for_figures(Summary, '');
end

%% ------------------------------------------------------------------------
% 4. Generate manuscript figure panels from rule-selectivity summary
% -------------------------------------------------------------------------

if saveFigs
    % Fig. 7B/F: pooled summary of rule-selective neurons.
    run_figure_block('Fig7B_F_rule_selectivity_summary', @() ...
        save_public_figure(fig_rule_pooled_2x3(Summary, days), saveDir, ...
        'Fig7B_F_rule_selectivity_summary', figFormats, closeFigs));

    % Fig. 7A: pooled heatmap of rule-selective activity.
    run_figure_block('Fig7A_rule_selectivity_heatmap', @() ...
        save_public_figure(fig_rule_pooled_heatmap_combo(NewData2_DAAS, Summary, days, Wsound, T, fs, correctOnly), ...
        saveDir, 'Fig7A_rule_selectivity_heatmap', figFormats, closeFigs));

    % Supplementary Fig. 5B: per-day heatmap grid.
    run_figure_block('SuppFig5B_rule_selectivity_per_day_heatmap', @() ...
        save_public_figure(fig_rule_pooled_heatmap_combo_perday(NewData2_DAAS, Summary, days, Wsound, T, fs, correctOnly), ...
        saveDir, 'SuppFig5B_rule_selectivity_per_day_heatmap', figFormats, closeFigs));

    % Supplementary Fig. 7C/G: sound versus early-window category mixture.
    run_figure_block('SuppFig7C_G_sound_vs_early_category_mix', @() ...
        save_public_figure(fig_window_mix_slope(Summary, days), saveDir, ...
        'SuppFig7C_G_sound_vs_early_category_mix', figFormats, closeFigs));

    % Supplementary Fig. 5H: pathway composition across days.
    run_figure_block('SuppFig5H_pathway_composition_slope', @() ...
        save_pathway_composition_figure(Summary, days, saveDir, figFormats, closeFigs, saveTables));

    % Supplementary Fig. 5G: pathway composition in Rule 1 versus Rule 2 cells.
    run_figure_block('SuppFig5G_pathway_rule_vs_rule', @() ...
        save_rule_vs_rule_pathway_figure(Summary, days, saveDir, figFormats, closeFigs, saveTables));
end

%% ------------------------------------------------------------------------
% 5. Spatial organization of rule-selective populations: Fig. 8E/F
% -------------------------------------------------------------------------
% These analyses ask whether neurons with similar rule-related activity are
% spatially clustered. The response correlation for each pair of neurons is
% related to the physical distance between their ROIs.

[T_animal_all, T_pooled_all] = corrdist_build_tables_from_soundcats( ...
    NewData2_DAAS, Summary, days, Wsound, Wearly, ...
    corrEdges, corrMinTrials, corrType, corrEqualWt, days);

[T_animal_day, T_pooled_day] = corrdist_build_tables_from_soundcats( ...
    NewData2_DAAS, Summary, days, Wsound, Wearly, ...
    corrEdges, corrMinTrials, corrType, corrEqualWt, corrDays);

if saveTables
    writetable(T_animal_all, fullfile(saveDir, 'source_Fig8F_corrdist_per_animal_all_days.csv'));
    writetable(T_pooled_all, fullfile(saveDir, 'source_Fig8F_corrdist_pooled_all_days.csv'));
    writetable(T_animal_day, fullfile(saveDir, 'source_Fig8E_corrdist_per_animal_target_day.csv'));
    writetable(T_pooled_day, fullfile(saveDir, 'source_Fig8E_corrdist_pooled_target_day.csv'));
end

if saveFigs
    % Fig. 8F: correlation-distance effect size over days.
    run_figure_block('Fig8F_corrdist_rho_over_days', @() ...
        save_corrdist_rho_over_days(T_animal_all, days, saveDir, figFormats, closeFigs, saveTables));

    % Fig. 8E: pair-level correlation-distance scatter plot for the target day.
    run_figure_block('Fig8E_corrdist_scatter', @() ...
        save_corrdist_scatter(NewData2_DAAS, Summary, days, Wsound, Wearly, ...
        corrMinTrials, corrType, corrDays, corrMaxPairs, corrMinDistPx, ...
        T_pooled_day, px_um, corrFit, saveDir, figFormats, closeFigs, saveTables));
end

%% ------------------------------------------------------------------------
% 6. Cross-day stability: Fig. 8G
% -------------------------------------------------------------------------
% This figure compares cross-day similarity for two types of signals:
%   1) pairs of neurons belonging to the same rule-selective category;
%   2) same cells matched across days by SCAD registration.

if saveFigs
    run_figure_block('Fig8G_crossday_stability_unified', @() ...
        save_crossday_stability_unified(NewData2_DAAS, Summary, days, ...
        stabilityExcludeDays, T, correctOnly, stability_minTrialsPerNeuron, ...
        stability_corr_type, scadMinDays, saveDir, figFormats, closeFigs, saveTables));
end

fprintf('\n[DAAS public] Finished manuscript-figure analysis.\n');
fprintf('[DAAS public] Outputs saved in: %s\n\n', saveDir);

end

