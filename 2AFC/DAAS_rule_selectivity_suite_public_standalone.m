function T_pairs = crossday_pairs_per_neuron_all_vs_all(NewData2_DAAS, Summary, days, excludeDays, T, correctOnly, minTrials, corrType)
% ALL-vs-ALL cross-day per-neuron correlations (full trace 1..T), same-category only.
% For each animal, for every day pair (i<j) excluding "excludeDays", and for each category:
%   - Build per-neuron mean traces using category-appropriate correct trials
%   - Compute ALL cross pairs between day i and day j neurons
% Output columns: animal, day_i, day_j, day_lag, category, rho, neuron_i, neuron_j

Ssound   = Summary(strcmpi(Summary.window,'Sound'), :);
haveTask = ismember('sig_task', Ssound.Properties.VariableNames);

% valid (non-excluded) days in original order
validDays = days(~ismember(string(days), string(excludeDays)));

rows = {};
animals = unique(Ssound.animal);
cats    = {'Rule1','Rule2','Non-rule'};

% Map day -> index for lag
day2idx = containers.Map(validDays, num2cell(1:numel(validDays)));

for ai = 1:numel(animals)
    A = string(animals(ai));
    Achar = char(A);

    % Skip animals not present
    if ~isfield(NewData2_DAAS, Achar), continue; end

    % Pre-slice SOUND rows for this animal
    Sa = Ssound(strcmpi(Ssound.animal, A), :);
    if isempty(Sa), continue; end

    % Iterate all day pairs (i<j)
    for ii = 1:numel(validDays)-1
        Di = validDays{ii};
        if ~isfield(NewData2_DAAS.(Achar), Di), continue; end
        Si = Sa(strcmpi(Sa.day, Di), :);
        if isempty(Si), continue; end

        for jj = ii+1:numel(validDays)
            Dj = validDays{jj};
            if ~isfield(NewData2_DAAS.(Achar), Dj), continue; end
            Sj = Sa(strcmpi(Sa.day, Dj), :);
            if isempty(Sj), continue; end

            lag = day2idx(Dj) - day2idx(Di);

            % Per category: gather neurons & traces on each day, then all-vs-all
            for ci = 1:numel(cats)
                cat = cats{ci};

                mi = category_mask(Si, cat, haveTask);
                mj = category_mask(Sj, cat, haveTask);
                list_i = double(Si.neuron(mi));
                list_j = double(Sj.neuron(mj));
                if isempty(list_i) || isempty(list_j), continue; end

                % Build traces for day i
                Tr_i = cell(numel(list_i),1); ok_i = false(numel(list_i),1);
                for k = 1:numel(list_i)
                    Tr_i{k} = collect_trace_for_neuron(NewData2_DAAS.(Achar).(Di), list_i(k), cat, T, correctOnly, minTrials);
                    ok_i(k) = ~isempty(Tr_i{k});
                end
                list_i = list_i(ok_i); Tr_i = Tr_i(ok_i);
                if isempty(list_i), continue; end

                % Build traces for day j
                Tr_j = cell(numel(list_j),1); ok_j = false(numel(list_j),1);
                for k = 1:numel(list_j)
                    Tr_j{k} = collect_trace_for_neuron(NewData2_DAAS.(Achar).(Dj), list_j(k), cat, T, correctOnly, minTrials);
                    ok_j(k) = ~isempty(Tr_j{k});
                end
                list_j = list_j(ok_j); Tr_j = Tr_j(ok_j);
                if isempty(list_j), continue; end

                % All cross pairs
                for p = 1:numel(Tr_i)
                    ti = Tr_i{p}(:);
                    if ~any(isfinite(ti)), continue; end
                    for q = 1:numel(Tr_j)
                        tj = Tr_j{q}(:);
                        if ~any(isfinite(tj)), continue; end
                        try
                            switch lower(corrType)
                                case 'pearson'
                                    r = corr(ti, tj, 'Type','Pearson','Rows','pairwise');
                                otherwise
                                    r = corr(ti, tj, 'Type','Spearman','Rows','pairwise');
                            end
                        catch
                            r = NaN;
                        end
                        if ~isfinite(r), continue; end
                        rows(end+1,:) = {A, Di, Dj, lag, cats{ci}, r, list_i(p), list_j(q)}; %#ok<AGROW>
                    end
                end
            end
        end
    end
end

if isempty(rows)
    T_pairs = table('Size',[0 8], ...
        'VariableTypes',{'string','string','string','double','string','double','double','double'}, ...
        'VariableNames',{'animal','day_i','day_j','day_lag','category','rho','neuron_i','neuron_j'});
else
    T_pairs = cell2table(rows, 'VariableNames', ...
        {'animal','day_i','day_j','day_lag','category','rho','neuron_i','neuron_j'});
end
end



function T_pairs = crossday_pairs_samecell_by_tracefield( ...
    NewData2_DAAS, Summary, days, stabilityExcludeDays, ...
    T, correctOnly, minTrialsPerNeuron, corrType, traceField)

% ------------- locate same-cell map -------------
[idMap, globalIds] = extract_samecell_idmap(Summary, NewData2_DAAS, days);
   % [nCells x nDays], ROI indices per day (NaN if missing)
nDays = numel(days);

% optional: exclude days
if ~isempty(stabilityExcludeDays)
    [~,exIdx] = ismember(stabilityExcludeDays, days);
    exIdx = exIdx(exIdx>0);
    idMap(:,exIdx) = NaN;
end

% ------------- build pairs -------------
rows_cell      = {};
rows_day_i     = [];
rows_day_j     = [];
rows_rho       = [];
rows_field     = {};
rows_animal    = {};
rows_roi_i     = [];
rows_roi_j     = [];

for c = 1:size(idMap,1)
    avail = find(~isnan(idMap(c,:)));
    if numel(avail) < 2
        continue; % need at least 2 days for this cell
    end

    % all unique day pairs (i<j)
    for ii = 1:numel(avail)-1
        di = avail(ii);
        roi_i = idMap(c, di);
        % fetch trace day i
        tr_i = fetch_trace_1D(NewData2_DAAS, days(di), roi_i, traceField, correctOnly, minTrialsPerNeuron);
        if isempty(tr_i) || numel(tr_i) ~= T, continue; end

        for jj = ii+1:numel(avail)
            dj = avail(jj);
            roi_j = idMap(c, dj);
            tr_j = fetch_trace_1D(NewData2_DAAS, days(dj), roi_j, traceField, correctOnly, minTrialsPerNeuron);
            if isempty(tr_j) || numel(tr_j) ~= T, continue; end

            % correlation (same as elsewhere in your pipeline)
            rho = safe_corr(tr_i(:), tr_j(:), corrType);


            rows_cell{end+1,1}  = globalIds(c);
            rows_day_i(end+1,1) = days(di);
            rows_day_j(end+1,1) = days(dj);
            rows_rho(end+1,1)   = rho;
            rows_field{end+1,1} = traceField;
            rows_animal{end+1,1}= try_get_animal_label(Summary, days(di)); % optional label
            rows_roi_i(end+1,1) = roi_i;
            rows_roi_j(end+1,1) = roi_j;
        end
    end
end

T_pairs = table( ...
    rows_cell, rows_animal, rows_day_i, rows_day_j, rows_roi_i, rows_roi_j, rows_field, rows_rho, ...
    'VariableNames', {'global_cell_id','animal','day_i','day_j','roi_i','roi_j','trace_field','rho'});
end

% ---------- helpers ----------
function [idMap, globalIds] = extract_samecell_idmap(Summary, NewData2_DAAS, days)
% Try Summary first, then build from NewData2_DAAS

% --- 1) Summary fast path (if present) ---
if ~isempty(Summary)
    if isfield(Summary,'SCADmap')
        idMap = Summary.SCADmap; globalIds = (1:size(idMap,1))'; return;
    end
    if isfield(Summary,'SCAD') && isfield(Summary.SCAD,'id_map')
        idMap = Summary.SCAD.id_map;
        if isfield(Summary.SCAD,'global_id'), globalIds = Summary.SCAD.global_id(:);
        else, globalIds = (1:size(idMap,1))'; end
        return;
    end
end

% --- 2) Construct from NewData2_DAAS ---
% We expect each day's struct to contain a per-ROI vector of global IDs:
% any of these: {'global_cell_id','global_id','globalID','CellGlobalID','SCAD_global_id'}
cand = {'global_cell_id','global_id','globalID','CellGlobalID','SCAD_global_id'};
gid_by_day = cell(numel(days),1);
for k = 1:numel(days)
    S = NewData2_DAAS{days(k)};
    gid = [];
    for c = 1:numel(cand)
        if isfield(S, cand{c}) && isnumeric(S.(cand{c})) && isvector(S.(cand{c}))
            gid = S.(cand{c})(:); break;
        end
        if isfield(S,'SCAD') && isstruct(S.SCAD) && isfield(S.SCAD, cand{c})
            x = S.SCAD.(cand{c});
            if isnumeric(x) && isvector(x), gid = x(:); break; end
        end
        if isfield(S,'ROIs') && isstruct(S.ROIs) && isfield(S.ROIs, cand{c})
            x = S.ROIs.(cand{c});
            if isnumeric(x) && isvector(x), gid = x(:); break; end
        end
    end
    if isempty(gid)
        error('No global cell id vector found in NewData2_DAAS on day index %d.', days(k));
    end
    gid_by_day{k} = gid;
end

% Collect universe of global ids
all_gids = unique(cell2mat(gid_by_day));
all_gids(isnan(all_gids)) = [];
globalIds = sort(all_gids(:));
nG = numel(globalIds); nD = numel(days);
idMap = NaN(nG, nD);

% Fill ROI index for each (global id, day) where present
for k = 1:nD
    gid = gid_by_day{k};
    % map from gid->roi index
    [~, loc] = ismember(gid, globalIds); % roi i has globalIds(loc(i))
    for roi = 1:numel(gid)
        gidx = loc(roi);
        if gidx>0
            idMap(gidx, k) = roi;
        end
    end
end
end



function tr = fetch_trace_1D(NewData2_DAAS, dayValue, roiIdx, traceField, correctOnly, minTrials)
% Returns a 1xT vector for that ROI and day from the chosen traceField.
% --- ADAPT THIS BLOCK to your actual data paths if needed ---
S = NewData2_DAAS{dayValue};              % e.g., sessions indexed by your "days" values
X = S.(traceField);                       % expected: nCells x T   OR   nCells x T x nTrials   (or similar)

if ndims(X) == 2
    tr = X(roiIdx, :);
    return;
end

% If you store trials, average across trials (respecting correctOnly if mask exists)
% Try to discover a correctness mask commonly used in your pipeline:
mask = [];
if isfield(S,'trial_is_correct'); mask = S.trial_is_correct(:)~=0; end
if isempty(mask) && isfield(S,'Correct'); mask = S.Correct(:)~=0; end
if isempty(mask) && isfield(S,'isCorrect'); mask = S.isCorrect(:)~=0; end
if isempty(mask)
    % Fallback: keep all trials
    mask = true(size(X,3),1);
end
if correctOnly
    mask = mask(:)~=0;
else
    mask = true(size(mask));
end

% Normalize shape and average across trials that pass mask
% Accept either nCells x T x nTrials or nCells x nTrials x T
sz = size(X);
if numel(sz)==3 && sz(1)==size(X,1) && sz(3)==numel(mask)
    tr = squeeze(nanmean(X(roiIdx,:,mask), 3));
elseif numel(sz)==3 && sz(2)==numel(mask)
    tr = squeeze(nanmean(X(roiIdx,mask,:), 2));
else
    % Last-resort: try to squeeze to [T x nTrials] and average
    tmp = squeeze(X(roiIdx,:,:));
    if size(tmp,2)==numel(mask)
        tr = nanmean(tmp(:,mask),2).';
    else
        tr = []; % give up cleanly; caller will skip this pair
    end
end

% (Optional) enforce minTrials if you track per-trace trial counts elsewhere
% If you expose a per-ROI trial count, check it here and set tr=[] if below minTrials
end

