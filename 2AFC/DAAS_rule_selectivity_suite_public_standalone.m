                if isempty(distVals), continue; end

                % Per-animal downsampling to keep panels light
                nPairs = numel(distVals);
                if nPairs > maxPairsPerAnimal
                    idx = randperm(nPairs, maxPairsPerAnimal);
                    distVals = distVals(idx); rVals = rVals(idx);
                end

                % Append
                rows{end+1,1} = repmat(string(A), numel(distVals),1); %#ok<AGROW>
                rows{end,2}   = repmat(string(D), numel(distVals),1);
                rows{end,3}   = repmat(string(winResp), numel(distVals),1);
                rows{end,4}   = repmat(string(catName), numel(distVals),1);
                rows{end,5}   = distVals(:);
                rows{end,6}   = rVals(:);
            end
        end
    end
end

if isempty(rows)
    T_pairs = table('Size',[0 6], 'VariableTypes',{'string','string','string','string','double','double'}, ...
        'VariableNames',{'animal','day','winResp','category','dist','r'});
    return;
end

T_pairs = table( vertcat(rows{:,1}), vertcat(rows{:,2}), vertcat(rows{:,3}), vertcat(rows{:,4}), ...
                 vertcat(rows{:,5}), vertcat(rows{:,6}), ...
    'VariableNames', {'animal','day','winResp','category','dist','r'} );
end


function [T_effAnimal, T_effPooled] = corrdist_effects_from_pairs(T_pairs)
% Compute per-animal effect sizes (Spearman rho and linear slope) and then
% pooled means across animals per day/window/category.

if isempty(T_pairs)
    T_effAnimal = table('Size',[0 7], 'VariableTypes',{'string','string','string','string','double','double','double'}, ...
        'VariableNames',{'animal','day','winResp','category','rho','slope','n_pairs'});
    T_effPooled = table('Size',[0 9], 'VariableTypes',{'string','string','string','double','double','double','double','double','double'}, ...
        'VariableNames',{'day','winResp','category','rho_mean','rho_sem','slope_mean','slope_sem','n_animals','n_pairs_total'});
    return;
end

% Per animal/day/window/category
[G, A, D, W, C] = findgroups(T_pairs.animal, T_pairs.day, T_pairs.winResp, T_pairs.category);
rho  = splitapply(@(x,y) local_spearman(x,y), T_pairs.dist, T_pairs.r, G);
slope= splitapply(@(x,y) local_linear_slope(x,y), T_pairs.dist, T_pairs.r, G);
npr  = splitapply(@(x) sum(isfinite(x)), T_pairs.r, G);

T_effAnimal = table(A, D, W, C, rho, slope, npr, ...
    'VariableNames', {'animal','day','winResp','category','rho','slope','n_pairs'});

% Pooled across animals (equal weight per animal)
[H, d2, w2, c2] = findgroups(T_effAnimal.day, T_effAnimal.winResp, T_effAnimal.category);
rho_mean   = splitapply(@(v) mean(v,'omitnan'), T_effAnimal.rho, H);
rho_sem    = splitapply(@(v) std(v,0,'omitnan')./sqrt(max(1,numel(v))), T_effAnimal.rho, H);
slope_mean = splitapply(@(v) mean(v,'omitnan'), T_effAnimal.slope, H);
slope_sem  = splitapply(@(v) std(v,0,'omitnan')./sqrt(max(1,numel(v))), T_effAnimal.slope, H);
n_anim     = splitapply(@(v) numel(v), T_effAnimal.rho, H);

% total pairs represented (sum over animals)
key = string(T_pairs.day) + "|" + string(T_pairs.winResp) + "|" + string(T_pairs.category);
[H2, d3, w3, c3] = findgroups(key);
npairs_total = splitapply(@(x) numel(x), key, H2); %#ok<NASGU> % we just need alignment below

% Build pooled table
T_effPooled = table(d2, w2, c2, rho_mean, rho_sem, slope_mean, slope_sem, n_anim, ...
    'VariableNames', {'day','winResp','category','rho_mean','rho_sem','slope_mean','slope_sem','n_animals'});
end

function r = local_spearman(x,y)
[r,~] = safe_corr_spearman(x,y);
end

function b1 = local_linear_slope(x,y)
% Simple least-squares slope of r ~ distance (robust enough for summary)
x = x(:); y = y(:);
