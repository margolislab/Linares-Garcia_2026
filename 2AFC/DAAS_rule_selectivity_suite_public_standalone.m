end


function SCAD = scad_table_from_csv(AnimalStruct, csvPath, days, T, correctOnly)
    % Read CSV
    Tcsv = readtable(csvPath);
    % Normalize names
    vn = lower(string(Tcsv.Properties.VariableNames));
    % First column is global ID
    gidCol = 1;
    gid = Tcsv{:, gidCol};
    gid = string(gid);  % keep as string IDs to be safe

    rows = {};
    for di = 1:numel(days)
        dayName = days{di};
        % find a column that matches this day (case-insensitive)
        colIdx = find(strcmpi(string(Tcsv.Properties.VariableNames), dayName), 1);
        if isempty(colIdx), continue; end

        roiCol = Tcsv{:, colIdx};
        for r = 1:numel(roiCol)
            roi = double(roiCol(r));
            if ~isfinite(roi) || roi<=0, continue; end
            % Guard: make sure the day exists and ROI exists
            if ~isfield(AnimalStruct, dayName), continue; end
            Eday = AnimalStruct.(dayName);
            if ~iscell(Eday) || roi>numel(Eday) || ~isfield(Eday{roi},'data') || isempty(Eday{roi}.data)
                continue;
            end

            X = Eday{roi}.data;
            Tuse = min(size(X,2), T);

            % masks
            [m1, m2] = get_correct_masks(Eday{roi}, size(X,1), correctOnly);
            Xc = X(1:numel(m1), 1:Tuse);

            % Mean traces on correct trials for each association
            thf = []; tlf = [];
            if any(m1)
                thf = mean(Xc(m1,:), 1, 'omitnan');  % HF == Rule1 in your SCAD convention
            end
            if any(m2)
                tlf = mean(Xc(m2,:), 1, 'omitnan');  % LF == Rule2 in your SCAD convention
            end

            % Pad to T
            if ~isempty(thf) && numel(thf)<T, thf = [thf, nan(1, T-numel(thf))]; end
            if ~isempty(tlf) && numel(tlf)<T, tlf = [tlf, nan(1, T-numel(tlf))]; end

            rows(end+1,:) = { gid(r), di, thf, tlf }; %#ok<AGROW>
        end
    end

    if isempty(rows)
        SCAD = table('Size',[0 4], 'VariableTypes',{'string','double','cell','cell'}, ...
                     'VariableNames', {'globalid','dayindex','tracehf','tracelf'});
        return;
    end

    SCAD = cell2table(rows, 'VariableNames', {'globalid','dayindex','tracehf','tracelf'});
end



function out = report_stats_LOAO(x, animal, labelStr, makePlot)
if nargin < 4 || isempty(makePlot), makePlot = false; end

% --- sanitize
x = x(:);
if iscell(animal), animal = string(animal); end
animal = categorical(animal(:));
ok = ~isnan(x) & ~isundefined(animal);
x = x(ok); animal = animal(ok);

if isempty(x)
    fprintf('\n=== %s — NO DATA (all NaN) ===\n', labelStr);
    out = struct('p',NaN,'HL',NaN,'delta',NaN);
    return
end

% --- FULL SAMPLE
[p,~,stats] = signrank(x, 0, 'method','approximate');         % one-sample vs 0
HL = hodges_lehmann_1samp(x);                                 % robust location
d  = cliffs_delta_vs_zero(x);                                  % vs 0
zv = NaN; if exist('stats','var') && isstruct(stats) && isfield(stats,'zval'), zv = stats.zval; end

fprintf('\n=== %s — FULL SAMPLE ===\n', labelStr);
fprintf('N=%d, median=%.4g, HLΔ=%.4g, Cliff δ=%.4g, signrank p=%.3g (Z=%.3g)\n', ...
        numel(x), median(x,'omitnan'), HL, d, p, zv);



% --- LOAO
ua = categories(animal);
fprintf('--- LOAO (drop one animal) ---\n');
for k = 1:numel(ua)
    keep = animal ~= ua{k};
    nkeep = nnz(keep);
    if nkeep < 3
        fprintf('drop %s → N=%d (skip)\n', ua{k}, nkeep);
        continue
    end
    xk = x(keep);
    [pk,~,statsk] = signrank(xk, 0, 'method','approximate');
    HLk = hodges_lehmann_1samp(xk);
    dk  = cliffs_delta_vs_zero(xk);
    zk = NaN; if exist('statsk','var') && isstruct(statsk) && isfield(statsk,'zval'), zk = statsk.zval; end
    fprintf('drop %s → N=%d, median=%.4g, HLΔ=%.4g, Cliff δ=%.4g, p=%.3g (Z=%.3g)\n', ...
            ua{k}, nkeep, median(xk,'omitnan'), HLk, dk, pk, zk);
end

out = struct('p',p,'HL',HL,'delta',d);

if makePlot
    % (optional) you can add a compact plot here; left empty to avoid noise
end
end

% ----- helpers -----
function HL = hodges_lehmann_1samp(x)
% One-sample Hodges–Lehmann estimator: median of Walsh averages (i <= j).

    % Ensure column and drop NaNs (robust)
    x = x(:);
    x = x(~isnan(x));

    n = numel(x);
    if n == 0
        HL = NaN; 
        return
    elseif n == 1
        HL = x(1);
        return
    end

    % All i<j pair means as a column
    idx = nchoosek(1:n, 2);
    pair_means = mean([x(idx(:,1)) x(idx(:,2))], 2);

    % Walsh set = x (i=j) plus pair means (i<j), all as a column
    walsh = [x; pair_means];

    % Robust location
    HL = median(walsh, 'omitnan');
end


function d = cliffs_delta_vs_zero(x)
pos = sum(x>0); neg = sum(x<0); ties = sum(x==0); %#ok<NASGU>
if pos+neg == 0, d = NaN; else, d = (pos - neg)/(pos + neg); end
end


function [chi2, df, p] = chi2_indep(Obs)
% Chi-square test of independence for a contingency table.
% Obs is k x m (counts).
    Obs = double(Obs);
    Obs(~isfinite(Obs)) = 0;

    rowS = sum(Obs,2);
    colS = sum(Obs,1);
    N    = sum(rowS);

    if N <= 0
        chi2 = NaN; df = NaN; p = NaN; return;
    end

    Exp  = (rowS * colS) / N;
    chi2 = sum(sum( (Obs - Exp).^2 ./ max(Exp, eps) ));
    df   = (size(Obs,1)-1) * (size(Obs,2)-1);

    % p-value (use chi2cdf if available, otherwise gammainc fallback)
    try
        p = 1 - chi2cdf(chi2, df);
    catch
        p = 1 - gammainc(chi2/2, df/2);  % base MATLAB fallback
    end
end

