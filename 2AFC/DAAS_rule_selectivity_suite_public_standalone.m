function T = corrdist_spearman_effects(T_pooled)
% Compute Spearman rho and p of r_mean vs bin_center for each (day, winResp, category).
% Expects columns: day, winResp, category, bin_center, r_mean
    if isempty(T_pooled)
        T = table('Size',[0 6], 'VariableTypes',{'string','string','string','double','double','double'}, ...
                  'VariableNames',{'day','winResp','category','rho','p_spearman','n_bins'});
        return;
    end

    [G, dG, wG, cG] = findgroups(T_pooled.day, T_pooled.winResp, T_pooled.category);

    rho = splitapply(@(x,y) local_spearman_r(x,y), T_pooled.bin_center, T_pooled.r_mean, G);
    p   = splitapply(@(x,y) local_spearman_p(x,y), T_pooled.bin_center, T_pooled.r_mean, G);
    n   = splitapply(@(x,y) sum(isfinite(x) & isfinite(y)), T_pooled.bin_center, T_pooled.r_mean, G);

    T = table(dG, wG, cG, rho, p, n, ...
        'VariableNames', {'day','winResp','category','rho','p_spearman','n_bins'});
end

