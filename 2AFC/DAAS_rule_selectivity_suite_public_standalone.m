function out = map_pathway_label(pathStr)
% Map 'pathway' free text to {'D1','A2a','Other'}
if ismissing(pathStr) || isempty(pathStr)
    out = "Other"; return;
end
s = lower(string(pathStr));
if contains(s, "a2a")
    out = "A2a";
elseif contains(s, "d1")
    out = "D1";
else
    out = "Other";
end
end

function T = summarize_pathway_pref_counts(Summary, days)
% Counts and percentages of D1/A2a within Rule1/Rule2/Non-rule classes,
% for both Sound and Early windows, aggregated per day.
% Non-rule = sig_task & ~sig_FDR (fallback to ~sig_FDR if sig_task missing).
haveTask = ismember('sig_task', Summary.Properties.VariableNames);
Wlist = {'Sound','Early'};

rows = {};
for wi = 1:numel(Wlist)
    Wname = Wlist{wi};
    S = Summary(strcmpi(Summary.window, Wname), :);
    if isempty(S), continue; end
    for d = 1:numel(days)
        Sd = S(strcmpi(S.day, days{d}), :);
        if isempty(Sd), continue; end

        % class masks
        isR1 = Sd.sig_FDR & Sd.auROC > 0.5;
        isR2 = Sd.sig_FDR & Sd.auROC < 0.5;
        if haveTask
            isNR = Sd.sig_task & ~Sd.sig_FDR;
        else
            isNR = ~Sd.sig_FDR;
        end

        % pathway reduced
        pth = arrayfun(@map_pathway_label, Sd.pathway);
        for cls = ["Rule1","Rule2","Non-rule"]
            switch cls
                case "Rule1", m = isR1;
                case "Rule2", m = isR2;
                otherwise,     m = isNR;
            end
            if ~any(m), continue; end
            p = pth(m);
            nD1  = sum(p=="D1");
            nA2a = sum(p=="A2a");
            nID  = nD1 + nA2a;  % identified only
            nAll = sum(m);      % includes "Other"

            rows(end+1,:) = { string(days{d}), Wname, cls, ...
                              nD1, nA2a, nID, nAll, ...
                              safe_div(nD1, nID), safe_div(nA2a, nID) }; %#ok<AGROW>
        end
    end
end

T = cell2table(rows, 'VariableNames', ...
    {'day','window','class','n_D1','n_A2a','n_IDed','n_totalClass','p_D1_of_ID','p_A2a_of_ID'});
end

function v = safe_div(a,b)
