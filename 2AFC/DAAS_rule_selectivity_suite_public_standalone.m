function [T_animal, T_pooled] = corrdist_build_tables_from_soundcats(NewData2_DAAS, Summary, days, Wsound, Wearly, edges, minTrials, corrType, equalWeightAnimals, dayList)
% Build per-animal and pooled tables of correlation vs distance.
% Neuron categories are defined using the SOUND window (sig_FDR/pref there; Non-rule via sig_task & ~sig_FDR).
% Correlations are computed separately for response windows: 'Sound' and 'Early'.
% Trial subsets per category:
%   Rule1: correct Rule1 trials only; Rule2: correct Rule2 trials only; Non-rule: all correct trials.

if nargin<10 || isempty(dayList), dayList = {'Five'}; end

% --- AUTO edges if requested or invalid ---
if (ischar(edges) && strcmpi(edges,'auto')) || (isstring(edges) && strcmpi(edges,"auto")) ...
        || isempty(edges) || numel(edges)<2
    edges = estimate_corrdist_edges(NewData2_DAAS, Summary, days, dayList);
end
centers = (edges(1:end-1) + edges(2:end))/2;


% Ensure columns exist
haveTask = ismember('sig_task', Summary.Properties.VariableNames);
if ~haveTask
    % fabricate a false column if missing
    Summary.sig_task = false(height(Summary),1);
end

% Restrict to SOUND rows for categorization only
Ssound = Summary(strcmpi(Summary.window,'Sound'), :);

% Prepare per-animal collector
T_animal = table('Size',[0 9], ...
    'VariableTypes', {'string','string','string','string','double','double','double','double','double'}, ...
    'VariableNames', {'animal','day','winResp','category','bin_center','r_mean','r_sem','n_pairs','n_animals_dummy'});

% We will fill pooled at the end by grouping T_animal
cats = {'Rule1','Rule2','Non-rule'};
winRespList = {'Sound','Early'};

animals = unique(Ssound.animal);
for ai = 1:numel(animals)
    A = animals(ai);
    Achar = char(A);
    for di = 1:numel(dayList)
        D = dayList{di};
        if ~ismember(D, days), continue; end
        % Need data present
        if ~isfield(NewData2_DAAS, Achar) || ~isfield(NewData2_DAAS.(Achar), D), continue; end

        % SOUND-based categorization for this animal/day
        Sd = Ssound(strcmpi(Ssound.animal,A) & strcmpi(Ssound.day,D), :);
        if isempty(Sd), continue; end

        % category masks (indices are "neuron" within this animal/day session)
        idx_R1 = Sd.sig_FDR & strcmpi(Sd.pref,'Rule1');
        idx_R2 = Sd.sig_FDR & strcmpi(Sd.pref,'Rule2');
        if haveTask
            idx_NR = Sd.sig_task & ~Sd.sig_FDR;
        else
            idx_NR = ~Sd.sig_FDR;  % fallback
        end

        fprintf('[CorrDist] %s/%s  R1=%d  R2=%d  NR=%d\n', Achar, D, sum(idx_R1), sum(idx_R2), sum(idx_NR));


        Neurons.R1 = double(Sd.neuron(idx_R1));
        Neurons.R2 = double(Sd.neuron(idx_R2));
        Neurons.NR = double(Sd.neuron(idx_NR));

        % Skip if nothing
        if isempty(Neurons.R1) && isempty(Neurons.R2) && isempty(Neurons.NR), continue; end

        % Compute pair correlations per response window
        for wr = 1:numel(winRespList)
            winResp = winRespList{wr};
            switch winResp
                case 'Sound', W = Wsound;
                case 'Early', W = Wearly;
                otherwise, W = Wsound;
            end
            if isempty(W), continue; end

            for c = 1:numel(cats)
                catName = cats{c}; % 'Rule1' | 'Rule2' | 'Non-rule'
                switch catName
                    case 'Rule1', listN = Neurons.R1; subsetTag = 'R1';
                    case 'Rule2', listN = Neurons.R2; subsetTag = 'R2';
                    otherwise,    listN = Neurons.NR; subsetTag = 'BOTH';
                end
                if numel(listN) < 2, continue; end

                % Compute per-pair distances and correlations
                [distVals, rVals] = corrdist_pairs_for_set(NewData2_DAAS.(Achar).(D), listN, W, subsetTag, minTrials, corrType);
                if isempty(distVals), continue; end

                % Bin
                [~,~,bin] = histcounts(distVals, edges);
                G = findgroups(bin(bin>0));
                rv = rVals(bin>0);
                bc = centers(unique(bin(bin>0)));
                r_mean = splitapply(@(x) mean(x,'omitnan'), rv, G);
                r_sem  = splitapply(@(x) std(x,0,'omitnan')/sqrt(max(1,numel(x))), rv, G);
                n_pairs= splitapply(@(x) sum(isfinite(x)), rv, G);

                % Append rows for this animal/day/winResp/category
                Ta = table(repmat(string(A),numel(bc),1), ...
                           repmat(string(D),numel(bc),1), ...
                           repmat(string(winResp),numel(bc),1), ...
                           repmat(string(catName),numel(bc),1), ...
                           bc(:), r_mean(:), r_sem(:), n_pairs(:), ...
                           repmat(1,numel(bc),1), ... % dummy=1 to count contributing animals/bins later
                           'VariableNames', {'animal','day','winResp','category','bin_center','r_mean','r_sem','n_pairs','n_animals_dummy'});
                T_animal = [T_animal; Ta]; %#ok<AGROW>
            end
        end
    end
end

% Pooled: average across animals (equal weight per animal per bin if equalWeightAnimals=true)
if isempty(T_animal)
    T_pooled = table('Size',[0 9], ...
        'VariableTypes', {'string','string','string','double','double','double','double','double','double'}, ...
        'VariableNames', {'day','winResp','category','bin_center','r_mean','r_sem','n_animals','n_pairs_total','r_sd_across_animals'});
    return;
end

keys = {'day','winResp','category','bin_center'};
if equalWeightAnimals
    % First average within animal is already done (r_mean per animal/bin). Now average across animals.
    [G, dayG, winG, catG, binG] = findgroups(T_animal.day, T_animal.winResp, T_animal.category, T_animal.bin_center);
    r_mean = splitapply(@(x) mean(x,'omitnan'), T_animal.r_mean, G);
    r_sd   = splitapply(@(x) std(x,0,'omitnan'), T_animal.r_mean, G);
    n_anim = splitapply(@(x) numel(unique(x)), T_animal.animal, G);  % animals counted per group
    % For display, compute SEM across animals
    r_sem  = r_sd ./ sqrt(max(1,n_anim));
    n_pairs_total = splitapply(@(x) nansum(x), T_animal.n_pairs, G);

    T_pooled = table(dayG, winG, catG, binG, r_mean, r_sem, n_anim, n_pairs_total, r_sd, ...
        'VariableNames', {'day','winResp','category','bin_center','r_mean','r_sem','n_animals','n_pairs_total','r_sd_across_animals'});
else
    % Weight by all pairs (pool all rVals); approximate using animal means weighted by n_pairs
    [G, dayG, winG, catG, binG] = findgroups(T_animal.day, T_animal.winResp, T_animal.category, T_animal.bin_center);
    % Weighted mean and SEM using pair counts as weights
    wmean = splitapply(@(m,w) sum(m.*w,'omitnan')/max(1,sum(w,'omitnan')), T_animal.r_mean, T_animal.n_pairs, G);
    % For SEM, we approximate via weighted SD across animal means
    w = T_animal.n_pairs;
    wsq = splitapply(@(m,w) sqrt( max(0, sum(w.*(m - (sum(m.*w,'omitnan')/max(1,sum(w,'omitnan')))).^2,'omitnan') / max(1,sum(w,'omitnan'))) ), T_animal.r_mean, w, G);
    n_anim = splitapply(@(x) numel(unique(x)), T_animal.animal, G);
    n_pairs_total = splitapply(@(x) nansum(x), T_animal.n_pairs, G);

    T_pooled = table(dayG, winG, catG, binG, wmean, wsq./sqrt(max(1,n_anim)), n_anim, n_pairs_total, wsq, ...
        'VariableNames', {'day','winResp','category','bin_center','r_mean','r_sem','n_animals','n_pairs_total','r_sd_across_animals'});
end
end

function [distVals, rVals] = corrdist_pairs_for_set(Eday, neuronList, W, subsetTag, minTrials, corrType)
% Eday: cell array of neuron entries for one animal/day
% neuronList: vector of neuron indices to pair
% subsetTag: 'R1' | 'R2' | 'BOTH'
% Returns vectors of distances and correlations (pairwise)
distVals = []; rVals = [];
if numel(neuronList) < 2, return; end

% Pre-cache coords and basic trial masks from the first neuron (global across neurons)
nAll = numel(Eday);
nL   = numel(neuronList);

% Quick function to get coord; skip missing
getCoord = @(n) getCoordSafe(Eday{n});


% Pair loops
for ii = 1:nL-1
    n1 = neuronList(ii);
    if n1<1 || n1>nAll || ~isfield(Eday{n1},'data') || isempty(Eday{n1}.data), continue; end
    c1 = getCoord(n1);
    if any(~isfinite(c1)), continue; end

    % Extract per-trial features once per neuron per pair-set? (We keep simple here.)
    for jj = ii+1:nL
        n2 = neuronList(jj);
        if n2<1 || n2>nAll || ~isfield(Eday{n2},'data') || isempty(Eday{n2}.data), continue; end
        c2 = getCoord(n2);
        if any(~isfinite(c2)), continue; end

        % Distance
        d = hypot(c1(1)-c2(1), c1(2)-c2(2));
        if ~isfinite(d), continue; end

        % Subset trials: we AND masks across neurons to ensure both have those correct trials
        [m1a, m2a] = get_correct_masks(Eday{n1}, size(Eday{n1}.data,1), true);
        [m1b, m2b] = get_correct_masks(Eday{n2}, size(Eday{n2}.data,1), true);
        switch upper(subsetTag)
            case 'R1', use = (m1a & m1b);
            case 'R2', use = (m2a & m2b);
            otherwise, use = ((m1a|m2a) & (m1b|m2b));
        end
        nUse = sum(use);
        if nUse < minTrials, continue; end

        % Per-trial window means
        Xi = Eday{n1}.data; Xj = Eday{n2}.data;
        Tuse = min([size(Xi,2), size(Xj,2), max(W)]);
        if Tuse < max(W), continue; end
        vi = mean(Xi(use, W), 2, 'omitnan');
        vj = mean(Xj(use, W), 2, 'omitnan');

        % Correlation
        try
            switch lower(corrType)
                case 'pearson'
                    r = corr(vi, vj, 'Type','Pearson','Rows','pairwise');
                otherwise
                    r = corr(vi, vj, 'Type','Spearman','Rows','pairwise');
            end
        catch
            r = NaN;
        end
        if ~isfinite(r), continue; end

        distVals(end+1,1) = d; %#ok<AGROW>
        rVals(end+1,1)    = r; %#ok<AGROW>
    end
end
end

