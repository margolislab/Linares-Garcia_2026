function save_corrdist_scatter(NewData2_DAAS, Summary, days, Wsound, Wearly, ...
    corrMinTrials, corrType, corrDays, corrMaxPairs, corrMinDistPx, ...
    T_pooled_day, px_um, corrFit, saveDir, figFormats, closeFigs, saveTables)
% Fig. 8E.

T_pairs = corrdist_collect_pairs_from_soundcats( ...
    NewData2_DAAS, Summary, days, Wsound, Wearly, ...
    corrMinTrials, corrType, corrDays, corrMaxPairs, corrMinDistPx);

if saveTables
    writetable(T_pairs, fullfile(saveDir, 'source_Fig8E_corrdist_pairs.csv'));
end

targetDay = choose_corrdist_target_day(T_pooled_day, corrDays);

if isempty(targetDay)
    error('Could not identify a target day for Fig. 8E correlation-distance scatter.');
end

if ~any(strcmpi(string(T_pairs.day), string(targetDay)))
    error('No pair-level correlation-distance rows were found for target day %s.', targetDay);
end

h = fig_corrdist_scatterfits_day(T_pairs, targetDay, px_um, corrFit, corrMaxPairs);
save_public_figure(h, saveDir, sprintf('Fig8E_corrdist_scatter_%s', targetDay), figFormats, closeFigs);
end

function targetDay = choose_corrdist_target_day(T_pooled_day, corrDays)
% Choose the requested day if present; otherwise use the first available day.

targetDay = '';

for k = 1:numel(corrDays)
    if ismember(string(corrDays{k}), string(T_pooled_day.day))
        targetDay = char(corrDays{k});
        return;
    end
end

uDays = unique(string(T_pooled_day.day), 'stable');
if ~isempty(uDays)
    targetDay = char(uDays(1));
end
end

