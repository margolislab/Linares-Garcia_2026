function [T_pairs, T_templates] = stability_build_category_pairs( ...
    NewData2_DAAS, Summary, days, Wsound, Wearly, correctOnly, T, ...
    winTag, corrType, minN)
% Build per-animal, per-day "templates" for each category using SOUND-based categorization,
% then compute cross-day (i<j) correlations between templates of the same category.
% Returns:
%   T_pairs: [animal, category, day_i, day_j, day_lag, rho, corr_type, window, n_neurons_i, n_neurons_j]
%   T_templates: one row per (animal, day, category) with the template trace stored in a cell

haveTask = ismember('sig_task', Summary.Properties.VariableNames);
Ssound   = Summary(strcmpi(Summary.window,'Sound'), :);

% choose frame window for correlation across time
switch lower(winTag)
    case 'sound'
        Wcorr = Wsound;
    case 'early'
        Wcorr = Wearly;
    otherwise
        Wcorr = 1:T; % 'Full'
end

cats = {'Rule1','Rule2','Non-rule'};
animals = unique(Ssound.animal,'stable');

rowsT = {};  % templates rows
for ai = 1:numel(animals)
    A = char(animals(ai));
    for di = 1:numel(days)
        D = days{di};
        if ~isfield(NewData2_DAAS, A) || ~isfield(NewData2_DAAS.(A), D)
            continue;
        end
        Sd = Ssound(strcmpi(Ssound.animal,A) & strcmpi(Ssound.day,D), :);
        if isempty(Sd), continue; end

        % category membership within THIS day (SOUND-based)
        isR1 = Sd.sig_FDR & Sd.auROC > 0.5;
        isR2 = Sd.sig_FDR & Sd.auROC < 0.5;
        if haveTask
            isNR = Sd.sig_task & ~Sd.sig_FDR;
        else
            isNR = ~Sd.sig_FDR;
        end

        % Collect mean-trace-per-neuron matrices (correct trials)
        H = struct('R1',[],'R2',[],'NR',[]);
        % Rule1 template source rows
        S1 = Sd(isR1,:);  if ~isempty(S1), H.R1 = collect_mean_trace_pool(NewData2_DAAS, S1, D, true,  correctOnly, T); end
        % Rule2 template source rows
        S2 = Sd(isR2,:);  if ~isempty(S2), H.R2 = collect_mean_trace_pool(NewData2_DAAS, S2, D, false, correctOnly, T); end
        % Non-rule template source rows
        if haveTask
            SNR = Sd(isNR,:); 
        else
            SNR = Sd(~Sd.sig_FDR,:); 
        end
        if ~isempty(SNR), H.NR = collect_mean_trace_pool_bothrules(NewData2_DAAS, SNR, D, correctOnly, T); end

        % Convert each to a single template (mean across neurons), respecting minN
        for c = 1:numel(cats)
            switch cats{c}
                case 'Rule1', M = H.R1;
                case 'Rule2', M = H.R2;
                otherwise,    M = H.NR;
            end
            nNeur = size(M,1);
            if nNeur >= minN && ~isempty(M)
                tpl = mean(M,1,'omitnan');
                % restrict to correlation window frames to avoid NaN blocks (but store full trace for matrices)
                tpl = ensure_row(tpl, T);
                rowsT(end+1,:) = { string(A), string(D), string(cats{c}), string(winTag), nNeur, {tpl} }; %#ok<AGROW>
            else
                % keep an empty row only if you prefer—here we skip to avoid clutter
            end
        end
    end
end

if isempty(rowsT)
    T_templates = cell2table(cell(0,6), 'VariableNames', ...
        {'animal','day','category','window','n_neurons','template'});
    T_pairs = cell2table(cell(0,11), 'VariableNames', ...
        {'animal','category','day_i','day_j','day_lag','rho','corr_type','window','n_neurons_i','n_neurons_j','n_animals_dummy'});
    return;
end

T_templates = cell2table(rowsT, 'VariableNames', ...
    {'animal','day','category','window','n_neurons','template'});

% --------- build cross-day pairs within animal & category ---------
rowsP = {};
for ai = 1:numel(animals)
    A = string(animals(ai));
    Ta = T_templates(strcmp(T_templates.animal,A), :);
    for c = 1:numel(cats)
        Tc = Ta(strcmpi(Ta.category, cats{c}), :);
        if height(Tc) < 2, continue; end

        % order by the 'days' list provided to the function
        [~, order] = ismember(Tc.day, string(days));
        [~, idxSort] = sort(order); Tc = Tc(idxSort,:);
        for i = 1:height(Tc)-1
            for j = i+1:height(Tc)
                day_i = char(Tc.day(i));  day_j = char(Tc.day(j));
                tpl_i = Tc.template{i};   tpl_j = Tc.template{j};
                if isempty(tpl_i) || isempty(tpl_j), continue; end

                % correlate over selected frame window (drop NaNs)
                r = safe_corr_generic(tpl_i, tpl_j, corrType, Wsound, Wearly, winTag, T);
                if ~isfinite(r), continue; end

                lag = abs(find(strcmp(days, day_i)) - find(strcmp(days, day_j)));
                rowsP(end+1,:) = { A, string(cats{c}), string(day_i), string(day_j), double(lag), double(r), ...
                                   string(corrType), string(winTag), double(Tc.n_neurons(i)), double(Tc.n_neurons(j)), 1 }; %#ok<AGROW>
            end
        end
    end
end

if isempty(rowsP)
    T_pairs = cell2table(cell(0,11), 'VariableNames', ...
        {'animal','category','day_i','day_j','day_lag','rho','corr_type','window','n_neurons_i','n_neurons_j','n_animals_dummy'});
else
    T_pairs = cell2table(rowsP, 'VariableNames', ...
        {'animal','category','day_i','day_j','day_lag','rho','corr_type','window','n_neurons_i','n_neurons_j','n_animals_dummy'});
end
end

function tpl = ensure_row(tpl, T)
tpl = tpl(:).';
if numel(tpl) < T, tpl = [tpl, nan(1, T-numel(tpl))]; else, tpl = tpl(1:T); end
end

function r = safe_corr_generic(x, y, corrType, Wsound, Wearly, winTag, T)
% Correlate x and y across the requested window; guard against NaNs and short vectors.
if nargin < 7, T = numel(x); end
switch lower(winTag)
    case 'sound', W = Wsound;
    case 'early', W = Wearly;
    otherwise,    W = 1:T;
end
if isempty(W), r = NaN; return; end
x = x(:); y = y(:);
nUse = min([numel(x), numel(y), max(W)]);
x = x(1:nUse); y = y(1:nUse);
use = false(nUse,1); use(W(W<=nUse)) = true;
ok  = use & isfinite(x) & isfinite(y);
x = x(ok); y = y(ok);
if numel(x) < 3 || numel(unique(x))<2 || numel(unique(y))<2
    r = NaN; return;
end
try
    r = corr(x, y, 'Type', corrType, 'Rows','pairwise');
catch
    r = NaN;
end
end

