function T_pairs = crossday_pairs_per_neuron_baseline_vs_others(NewData2_DAAS, Summary, days, baselineDay, excludeDays, T, correctOnly, minTrials, corrType)
% Build all-vs-all per-neuron correlations of FULL traces (1..T frames)
% between a baseline day and every other (non-excluded) day, within the same category.
% Categories are defined from SOUND-window classification in Summary.
%
% Output columns: animal, baseline_day, other_day, category, rho, neuron_i, neuron_j

Ssound = Summary(strcmpi(Summary.window,'Sound'), :);
haveTask = ismember('sig_task', Ssound.Properties.VariableNames);
cats = {'Rule1','Rule2','Non-rule'};
rows = {};

animals = unique(Ssound.animal);
for ai = 1:numel(animals)
    A = string(animals(ai));
    Achar = char(A);
    if ~isfield(NewData2_DAAS, Achar) || ~isfield(NewData2_DAAS.(Achar), baselineDay), continue; end

    % Subtable for baseline day (classification from SOUND)
    Sb = Ssound(strcmpi(Ssound.animal,A) & strcmpi(Ssound.day,baselineDay), :);
    if isempty(Sb), continue; end

    for ci = 1:numel(cats)
        cat = cats{ci};

        % Neurons in baseline day for this category
        mb = category_mask(Sb, cat, haveTask);
        listBase = double(Sb.neuron(mb));
        if isempty(listBase), continue; end

        % Precompute baseline traces (full-length 1..T)
        baseTr = cell(numel(listBase),1);
        okB = false(numel(listBase),1);
        for i = 1:numel(listBase)
            baseTr{i} = collect_trace_for_neuron(NewData2_DAAS.(Achar).(baselineDay), listBase(i), cat, T, correctOnly, minTrials);
            okB(i) = ~isempty(baseTr{i});
        end
        listBase = listBase(okB);
        baseTr   = baseTr(okB);
        if isempty(listBase), continue; end

        % Compare to all OTHER days (excluding baseline & excludeDays)
        for d = 1:numel(days)
            D = days{d};
            if strcmpi(D, baselineDay) || any(strcmpi(D, excludeDays)), continue; end
            if ~isfield(NewData2_DAAS.(Achar), D), continue; end

            Sd = Ssound(strcmpi(Ssound.animal,A) & strcmpi(Ssound.day,D), :);
            if isempty(Sd), continue; end

            md = category_mask(Sd, cat, haveTask);
            listOther = double(Sd.neuron(md));
            if isempty(listOther), continue; end

            otherTr = cell(numel(listOther),1);
            okO = false(numel(listOther),1);
            for j = 1:numel(listOther)
                otherTr{j} = collect_trace_for_neuron(NewData2_DAAS.(Achar).(D), listOther(j), cat, T, correctOnly, minTrials);
                okO(j) = ~isempty(otherTr{j});
            end
            listOther = listOther(okO);
            otherTr   = otherTr(okO);
            if isempty(listOther), continue; end

            % All-vs-all pairs
            for i = 1:numel(baseTr)
                ti = baseTr{i}(:);
                for j = 1:numel(otherTr)
                    tj = otherTr{j}(:);
                    if ~any(isfinite(ti)) || ~any(isfinite(tj)), continue; end
                    try
                        switch lower(corrType)
                            case 'pearson'
                                r = corr(ti, tj, 'Type','Pearson','Rows','pairwise');
                            otherwise
                                r = corr(ti, tj, 'Type','Spearman','Rows','pairwise');
                        end
                    catch
                        r = NaN;
                    end
                    if ~isfinite(r), continue; end
                    rows(end+1,:) = {A, baselineDay, D, cat, r, listBase(i), listOther(j)}; %#ok<AGROW>
                end
            end
        end
    end
end

if isempty(rows)
    T_pairs = table('Size',[0 7], ...
        'VariableTypes',{'string','string','string','string','double','double','double'}, ...
        'VariableNames',{'animal','baseline_day','other_day','category','rho','neuron_i','neuron_j'});
else
    T_pairs = cell2table(rows, 'VariableNames', ...
        {'animal','baseline_day','other_day','category','rho','neuron_i','neuron_j'});
end
end

function m = category_mask(Sd, catName, haveTask)
% Mask rows of a SOUND-window subtable Sd by category label
au  = Sd.auROC; sig = Sd.sig_FDR;
switch catName
    case 'Rule1', m = sig & au > 0.5;
    case 'Rule2', m = sig & au < 0.5;
    otherwise
        if haveTask, m = Sd.sig_task & ~sig; else, m = ~sig; end
end
end

function tr = collect_trace_for_neuron(Eday, n, catName, T, correctOnly, minTrials)
% Mean trace across ALL frames (1..T) and relevant correct trials for this category.
tr = [];
if n<1 || n>numel(Eday) || ~isfield(Eday{n},'data') || isempty(Eday{n}.data)
    return;
end
X = Eday{n}.data;
[nTrials, Tcol] = size(X);
Tuse = min(Tcol, T);

[m1, m2] = get_correct_masks(Eday{n}, nTrials, correctOnly);
switch catName
    case 'Rule1', use = m1;
    case 'Rule2', use = m2;
    otherwise,    use = (m1 | m2);
end
if sum(use) < minTrials, return; end

Xc = X(1:numel(use), 1:Tuse);
tr = mean(Xc(use, :), 1, 'omitnan');

% pad/clip to T
if numel(tr) < T
    tr = [tr, nan(1, T-numel(tr))];
else
    tr = tr(1:T);
end
end

