        r1   = sum(Sd.sig_FDR & Sd.auROC>0.5);
        r2   = sum(Sd.sig_FDR & Sd.auROC<0.5);
        nonR = sum(Sd.sig_task & ~Sd.sig_FDR);

        P(d,:) = 100*[r1, r2, nonR] / max(1,total);

        R1(d)=r1; R2(d)=r2; NR(d)=nonR; TOT(d)=total;
    end

    % ---- Plot (bar) first ----
    bar(ax3, P, 'stacked');
    xticks(ax3, 1:numel(days)); xticklabels(ax3, days);
    ylim(ax3, [0 110]); % headroom for text
    ylabel(ax3, '% of all neurons');
    title(ax3, sprintf('%s — categories', Wname));
    legend(ax3, {'Rule1-pref','Rule2-pref','Non-rule-modulated'}, 'Location','eastoutside');
    grid(ax3,'on');

    % --- Chi-square across days (exclude Reversal) for category composition ---
    use = ~contains(lower(string(days)), "reversal") & isfinite(TOT) & TOT>0;

    if nnz(use) >= 2
        UN = TOT - (R1 + R2 + NR); % unmodulated remainder
        Obs_cat = [R1(use)', R2(use)', NR(use)', UN(use)'];   % day x 4 categories
        [chi2c, dfc, pc] = chi2_indep(Obs_cat);

        if pc < alpha, sigStr = 'SIGNIFICANT'; else, sigStr = 'n.s.'; end

        % ---- PRINT TO CONSOLE ----
        fprintf('[%s | category composition across days (excl Reversal)] chi2(%d)=%.3f, p=%.4g --> %s\n', ...
            Wname, dfc, chi2c, pc, sigStr);
        fprintf('Obs_cat (rows=days used; cols=[R1 R2 NR UN]):\n');
        disp(Obs_cat);

