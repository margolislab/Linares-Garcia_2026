function Summary = append_window(Summary, A, D, winTag, au, p, sigRule, sigTask, E)
%APPEND_WINDOW Append one window's rows into Summary.
%   Keeps: animal, day, neuron index, window, auROC, p_perm, sig_FDR, pref, pathway, sig_task
    if isempty(au) || isempty(p), return; end
    au = au(:); p = p(:);
    if nargin < 7 || isempty(sigRule), sigRule = false(size(au)); end
    if nargin < 8 || isempty(sigTask), sigTask = false(size(au)); end
    if nargin < 9, E = {}; end

    vld = isfinite(au) & isfinite(p);
    if ~any(vld), return; end

    idx = find(vld);
    auV = au(vld);
    pV  = p(vld);
    sR  = logical(sigRule(vld));
    sT  = logical(sigTask(vld));

    pref = repmat("Tie", numel(auV), 1);
    pref(auV > 0.5) = "Rule1";
    pref(auV < 0.5) = "Rule2";

    path = repmat("Unknown", numel(auV), 1);
    if ~isempty(E) && iscell(E)
        for k = 1:numel(idx)
            n = idx(k);
            if n <= numel(E) && isstruct(E{n}) && isfield(E{n},'neuronType') && ~isempty(E{n}.neuronType)
                path(k) = string(E{n}.neuronType);
            end
        end
    end

    Tadd = table( ...
        repmat(string(A), numel(auV), 1), ...
        repmat(string(D), numel(auV), 1), ...
        double(idx(:)), ...
        repmat(string(winTag), numel(auV), 1), ...
        double(auV(:)), ...
        double(pV(:)), ...
        logical(sR(:)), ...
        string(pref(:)), ...
        string(path(:)), ...
        logical(sT(:)), ...
        'VariableNames', {'animal','day','neuron','window','auROC','p_perm','sig_FDR','pref','pathway','sig_task'} ...
    );
    Summary = [Summary; Tadd];
end

