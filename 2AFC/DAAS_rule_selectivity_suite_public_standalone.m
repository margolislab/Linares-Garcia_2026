    ax3 = nexttile(tlo,(r-1)*3+3);

    P = nan(numel(days),3); % [Rule1, Rule2, NonR]
    R1 = nan(1,numel(days)); R2 = R1; NR = R1; TOT = R1;

    for d=1:numel(days)
        Sd = S(strcmpi(S.day,days{d}),:);
        if isempty(Sd), continue; end
