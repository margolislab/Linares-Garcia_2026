function p = paired_perm_p(diffs, nPerm)
% Sign-flip permutation on paired differences across days
d = diffs(isfinite(diffs));
if isempty(d), p = NaN; return; end
obs = abs(mean(d));
cnt = 0;
for k = 1:nPerm
    sgn = (rand(size(d))>0.5)*2 - 1;
    if abs(mean(d .* sgn)) >= obs
        cnt = cnt + 1;
    end
end
p = cnt / nPerm;
end

