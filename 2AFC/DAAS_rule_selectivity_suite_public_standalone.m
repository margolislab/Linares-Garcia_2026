function [TpairsHF, TpairsLF] = samecell_pairs_from_SCAD(SCAD, corrType)
% SCAD: table with columns:
%   globalid, day, dayindex, roi, neuronidx, tracehf, tracelf
% tracehf/tracelf can be cell-of-1xT or numeric NxT
uids = unique(SCAD.globalid(:));
HF_g = []; LF_g = [];
for k = 1:numel(uids)
    gid = uids(k);
    rows = find(SCAD.globalid == gid);
    if numel(rows) < 2, continue; end
    % all cross-day pairs (i<j)
    for a = 1:numel(rows)-1
        for b = a+1:numel(rows)
            i = rows(a); j = rows(b);

            xh = get_trace_column(SCAD.tracehf, i);
            yh = get_trace_column(SCAD.tracehf, j);
            xl = get_trace_column(SCAD.tracelf, i);
            yl = get_trace_column(SCAD.tracelf, j);

            rhoHF = safe_corr(xh, yh, corrType);
            rhoLF = safe_corr(xl, yl, corrType);

