    writetable(T_stats, fullfile(saveDir, 'source_Fig8G_pairwise_statistics.csv'));
end

save_public_figure(h, saveDir, 'Fig8G_crossday_stability_unified', figFormats, closeFigs);
end

function [hUnified, T_stats] = fig_crossday_stability_unified_public(T_pairNeur_all, T_sameHF, T_sameLF)
% Build the public version of Fig. 8G.
%
% The first three panels show cross-day correlations between neurons that
% belong to the same rule category. The last two panels show cross-day
% correlations for the same cells matched across days.

[corrCol, catCol] = find_corr_and_category_columns(T_pairNeur_all);

categoryLabels = string(T_pairNeur_all.(catCol));
rhoValues = double(T_pairNeur_all.(corrCol));

validRows = isfinite(rhoValues) & categoryLabels ~= "" & ~ismissing(categoryLabels);
categoryLabels = categoryLabels(validRows);
rhoValues = rhoValues(validRows);

preferredOrder = ["Rule1"; "Rule2"; "Non-rule"];
presentPreferred = preferredOrder(ismember(preferredOrder, unique(categoryLabels)));
remaining = setdiff(unique(categoryLabels, 'stable'), presentPreferred, 'stable');
