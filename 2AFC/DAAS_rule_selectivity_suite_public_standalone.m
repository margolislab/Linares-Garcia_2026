function q = bh_fdr_local(p)
% Benjamini–Hochberg FDR (returns q-values), works without toolboxes
p = p(:);
q = nan(size(p));
v = isfinite(p);
if ~any(v), return; end

pv = p(v);

% If you have Statistics Toolbox, mafdr is fine too:
if exist('mafdr','file')==2
    qv = mafdr(pv,'BHFDR',true);
    q(v) = qv;
    return;
end

% Toolbox-free BH-FDR:
[ps, ord] = sort(pv);              % sort p-values
m = numel(ps);
r = (1:m)';                        % ranks
qtmp = ps .* m ./ r;               % BH estimate
for i = m-1:-1:1                   % enforce monotonicity
    qtmp(i) = min(qtmp(i), qtmp(i+1));
end
qtmp = min(qtmp, 1);

qv = nan(m,1);
qv(ord) = qtmp;                    % unsort back to original pv order
q(v) = qv;
end