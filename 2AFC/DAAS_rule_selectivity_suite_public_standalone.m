function T_rho = corrdist_rho_from_binmeans(T_animal)
% Input: T_animal with columns: animal, day, winResp, category, bin_center, r_mean
% Output: pooled per day/window/category: rho_mean, rho_sem, n_animals

if isempty(T_animal)
    T_rho = table('Size',[0 6], ...
        'VariableTypes',{'string','string','string','double','double','double'}, ...
        'VariableNames',{'day','winResp','category','rho_mean','rho_sem','n_animals'});
    return;
